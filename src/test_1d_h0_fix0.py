# ==========================================================
# CHANGED:
# Gaussian branch được sửa để giống logic file train sb3:
# - v_base_vec vẫn lấy từ GP zero-mean như cũ
# - nhưng target modulation KHÔNG còn là b * g_mod với b cố định
# - thay vào đó, mỗi episode sample 1 relative amplitude trong
#   [target_mod_relative_amplitude_min, target_mod_relative_amplitude_max]
# - rồi modulation = sampled_amp * target_base * g_mod
# - sau đó trừ mean(modulation) giống file sb3
# ==========================================================
# ======================================================================
def _sample_gp_based_target_base_and_target(
    rng: np.random.Generator,
    x_grid: np.ndarray,
    cfg: ColdSpray1DConfig,
    dx: float,
    forced_target_mod_relative_amplitude: Optional[float] = None,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, float]:
    g_base = _sample_zero_mean_gp(
        rng=rng,
        x_grid=x_grid,
        std=cfg.gp_std,
        lengthscale=cfg.gp_lengthscale,
        jitter=cfg.gp_jitter,
    )

    v_mean = float(cfg.base_v)
    a = float(cfg.v_base_gp_amplitude)
    v_base_raw = v_mean + a * g_base.astype(np.float64)
    v_base_vec = np.clip(v_base_raw, cfg.v_min, cfg.v_max).astype(np.float32)

    target_base = (cfg.feed_rate * dx / np.maximum(v_base_vec, 1e-12)).astype(np.float32)

    g_mod = _sample_zero_mean_gp(
        rng=rng,
        x_grid=x_grid,
        std=cfg.gp_std,
        lengthscale=cfg.gp_lengthscale,
        jitter=cfg.gp_jitter,
    )

    # ==========================================================
    # CHANGED:
    # Sample relative GP amplitude giống file train sb3.
    # ==========================================================
    # ==========================================================
    # CHANGED:
    # Cho phép FIX amplitude khi evaluate robustness plot.
    # - nếu forced_target_mod_relative_amplitude != None: dùng giá trị đó
    # - nếu không: vẫn sample ngẫu nhiên trong [min, max] như trước
    # ==========================================================
    if forced_target_mod_relative_amplitude is None:
        sampled_target_mod_relative_amplitude = float(
            rng.uniform(
                cfg.target_mod_relative_amplitude_min,
                cfg.target_mod_relative_amplitude_max,
            )
        )
    else:
        sampled_target_mod_relative_amplitude = float(forced_target_mod_relative_amplitude)

    target_modulation = (
        sampled_target_mod_relative_amplitude
        * target_base.astype(np.float64)
        * g_mod.astype(np.float64)
    ).astype(np.float32)

    # ==========================================================
    # CHANGED:
    # Trừ mean(modulation) giống file train sb3 để modulation có mean ~ 0.
    # ==========================================================
    target_modulation = (target_modulation - np.mean(target_modulation)).astype(np.float32)
    target = np.maximum(target_base + target_modulation, 0.0).astype(np.float32)

    return v_base_vec, target_base, target, target_modulation, g_base, g_mod, sampled_target_mod_relative_amplitude

def _rectangular_bump(
    x_grid: np.ndarray,
    center: float,
    width: float,
    amp: float,
) -> np.ndarray:
    half_w = 0.5 * width
    left = center - half_w
    right = center + half_w
    mask = (x_grid >= left) & (x_grid <= right)
    bump = np.zeros_like(x_grid, dtype=np.float32)
    bump[mask] = np.float32(amp)
    return bump


def _circular_bump(
    x_grid: np.ndarray,
    center: float,
    width: float,
    amp: float,
) -> np.ndarray:
    # ==========================================================
    # NEW:
    # Circular bump dạng "nắp tròn".
    # - width là bề rộng toàn phần của bump
    # - radius = width / 2
    # - trong vùng |x-center| <= radius:
    #       y = amp * sqrt(1 - (d/radius)^2)
    # - ngoài vùng đó: y = 0
    #
    # Như vậy bump:
    # - cực đại = amp tại center
    # - chạm 0 mượt ở hai mép
    # - khác rect ở chỗ không có đỉnh phẳng
    # ==========================================================
    radius = 0.5 * width
    if radius <= 0.0:
        return np.zeros_like(x_grid, dtype=np.float32)

    d = (x_grid - center) / radius
    inside = np.maximum(0.0, 1.0 - d * d)
    bump = amp * np.sqrt(inside)

    # ép ngoài support về 0 rõ ràng để tránh sai số số học rất nhỏ
    bump[np.abs(x_grid - center) > radius] = 0.0
    return bump.astype(np.float32)

def _triangular_bump(
    x_grid: np.ndarray,
    center: float,
    width: float,
    amp: float,
) -> np.ndarray:
    # ==========================================================
    # Triangle bump:
    # - đỉnh tại center với giá trị amp
    # - tuyến tính giảm về 0 ở 2 mép
    # - support: |x-center| <= width/2
    #
    # formula:
    #   bump(x) = amp * max(0, 1 - |x-center| / (width/2))
    # ==========================================================
    half_w = 0.5 * width
    if half_w <= 0.0:
        return np.zeros_like(x_grid, dtype=np.float32)

    d = np.abs(x_grid - center)
    bump = amp * np.maximum(0.0, 1.0 - d / half_w)

    bump[d > half_w] = 0.0
    return bump.astype(np.float32)


def _compute_rect_bump_area(
    amp: float,
    width: float,
) -> float:
    # ==========================================================
    # NEW:
    # Rect bump area = amp * width
    # ==========================================================
    return float(amp * width)


def _compute_rect_normalized_severity_from_area(
    bump_area: float,
    target_base: np.ndarray,
    x_max: float,
    eps: float = 1e-12,
) -> float:
    # ==========================================================
    # NEW:
    # severity = bump_area / (mean(target_base) * x_max)
    # target_base cố định ở mode rect => mẫu số cố định.
    # ==========================================================
    mean_target_base = float(np.mean(target_base.astype(np.float64)))
    denom = max(mean_target_base * float(x_max), eps)
    return float(bump_area / denom)


def _compute_rect_bump_area_from_normalized_severity(
    normalized_severity: float,
    target_base: np.ndarray,
    x_max: float,
) -> float:
    # ==========================================================
    # NEW:
    # Đảo công thức severity để suy ra area cần có:
    # bump_area = severity * mean(target_base) * x_max
    # ==========================================================
    mean_target_base = float(np.mean(target_base.astype(np.float64)))
    return float(normalized_severity * mean_target_base * float(x_max))





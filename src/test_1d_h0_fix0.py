def make_venv(cfg: ColdSpray1DConfig, vecnormalize_path: str) -> VecNormalize:
    def make_env():
        return Monitor(ColdSpray1DEnv(cfg))

    base_venv = DummyVecEnv([make_env for _ in range(cfg.n_envs)])
    venv = VecNormalize.load(vecnormalize_path, base_venv)
    venv.training = False
    venv.norm_reward = False
    return venv

def rollout_model(
    model: PPO,
    venv: VecNormalize,
    cfg: ColdSpray1DConfig,
    deterministic: bool,
    max_steps: Optional[int] = None,
    preset_episode_setup: Optional[Dict[str, np.ndarray]] = None,
    reset_seed: Optional[int] = None,
    forced_target_mod_relative_amplitude: Optional[float] = None,
    forced_rect_normalized_severity: Optional[float] = None,
    forced_circular_normalized_severity: Optional[float] = None,
    forced_triangle_normalized_severity: Optional[float] = None,
):
    env = ColdSpray1DEnv(cfg)

    # ==========================================================
    # NEW:
    # Nếu có preset_episode_setup thì reset bằng setup đó
    # để 2 rollout dùng cùng target.
    # ==========================================================
    if preset_episode_setup is None:
        reset_options: Dict[str, Any] = {}
        if forced_target_mod_relative_amplitude is not None:
            reset_options["forced_target_mod_relative_amplitude"] = float(forced_target_mod_relative_amplitude)
        if forced_rect_normalized_severity is not None:
            reset_options["forced_rect_normalized_severity"] = float(forced_rect_normalized_severity)
        # ADDED FOR CIRCULAR ROBUSTNESS PLOT:
        # Truyền forced circular severity vào env.reset() khi cần.
        if forced_circular_normalized_severity is not None:
            reset_options["forced_circular_normalized_severity"] = float(forced_circular_normalized_severity)
        # ======================================================
        # ADDED FOR TRIANGLE ROBUSTNESS PLOT:
        # Truyền forced triangle severity vào env.reset() khi cần.
        # ======================================================
        if forced_triangle_normalized_severity is not None:
            reset_options["forced_triangle_normalized_severity"] = float(forced_triangle_normalized_severity)
        obs, _ = env.reset(seed=reset_seed, options=reset_options)
    else:
        obs, _ = env.reset(
            seed=reset_seed,
            options={"preset_episode_setup": preset_episode_setup},
        )

    n = cfg.n_bins
    T = cfg.n_steps if max_steps is None else max_steps

    heights: List[np.ndarray] = [obs[:n].copy()]
    xs: List[float] = [0.0]
    vs: List[float] = [float(obs[2 * n + 2])]
    mses: List[float] = []
    ov_maxs: List[float] = []
    losses: List[float] = []
    rewards: List[float] = []
    reasons: List[str] = [""]

    for _ in range(T):
        obs_norm = venv.normalize_obs(obs[None, :].astype(np.float32))
        act, _ = model.predict(obs_norm, deterministic=deterministic)
        obs, r, terminated, truncated, info = env.step(act[0])

        heights.append(obs[:n].copy())
        xs.append(float(info["nozzle_x"]))
        vs.append(float(info["velocity"]))
        mses.append(float(info["mse"]))
        ov_maxs.append(float(info["max_overshoot"]))
        losses.append(float(info["mse"]))
        rewards.append(float(r))
        reasons.append(str(info.get("termination_reason", "") or ""))

        if terminated or truncated:
            break

    return {
        "episode_setup": env._export_episode_setup(),   # NEW
        "x_grid": env.x_grid.copy(),
        "target": env.target.copy(),
        "target_base": env.target_base.copy(),
        "v_base_vec": env.v_base_vec.copy(),
        "base_profile": env.base_profile.copy(),
        "g_base": env.g_base.copy(),
        "g_mod": env.g_mod.copy(),
        "target_modulation": env.target_modulation.copy(),
        # CHANGED: lưu amplitude thật sự để robustness plot dùng trực tiếp
        "sampled_target_mod_relative_amplitude": float(env.sampled_target_mod_relative_amplitude),
        # NEW: lưu rect meta để severity plot dùng trực tiếp
        "rect_amp": float(env.rect_amp),
        "rect_width": float(env.rect_width),
        "rect_center": float(env.rect_center),
        "rect_bump_area": float(env.rect_bump_area),
        "rect_normalized_severity": float(env.rect_normalized_severity),
        # ======================================================
        # ADDED FOR CIRCULAR ROBUSTNESS PLOT:
        # lưu circular meta để circular severity plot dùng trực tiếp.
        # ======================================================
        "circ_amp": float(env.circ_amp),
        "circ_width": float(env.circ_width),
        "circ_center": float(env.circ_center),
        "circ_bump_area": float(env.circ_bump_area),
        "circ_normalized_severity": float(env.circ_normalized_severity),
        # ======================================================
        # ADDED FOR TRIANGLE ROBUSTNESS PLOT:
        # lưu triangle meta để triangle severity plot dùng trực tiếp.
        # ======================================================
        "tri_amp": float(env.tri_amp),
        "tri_width": float(env.tri_width),
        "tri_center": float(env.tri_center),
        "tri_bump_area": float(env.tri_bump_area),
        "tri_normalized_severity": float(env.tri_normalized_severity),
        "heights": np.stack(heights, axis=0),
        "xs": np.array(xs, dtype=np.float32),
        "vs": np.array(vs, dtype=np.float32),
        "mses": np.array(mses, dtype=np.float32),
        "ov_maxs": np.array(ov_maxs, dtype=np.float32),
        "losses": np.array(losses, dtype=np.float32),
        "rewards": np.array(rewards, dtype=np.float32),
        "reasons": reasons,
    }


def _compute_relative_error_metrics(
    final_height: np.ndarray,
    target: np.ndarray,
    eps: float = 1e-12,
) -> Dict[str, float]:
    err = final_height - target
    abs_target = np.maximum(np.abs(target), eps)
    mean_target_height = float(np.maximum(np.mean(abs_target), eps))

    # Mentor-oriented metric:
    # relative MSE normalized by target height scale.
    # We keep BOTH common normalizations he mentioned:
    # 1) pointwise normalization by target height
    # 2) global normalization by mean target height
    rel_err_pointwise = err / abs_target
    relative_mse_pointwise = float(np.mean(rel_err_pointwise ** 2))
    relative_rmse_pointwise_percent = float(100.0 * np.sqrt(relative_mse_pointwise))

    relative_mse_mean_target = float(np.mean(err ** 2) / (mean_target_height ** 2))
    relative_rmse_mean_target_percent = float(100.0 * np.sqrt(relative_mse_mean_target))

    mean_absolute_percentage_error = float(100.0 * np.mean(np.abs(err) / abs_target))

    return {
        "relative_mse_pointwise": relative_mse_pointwise,
        "relative_mse_mean_target": relative_mse_mean_target,
        "relative_rmse_pointwise_percent": relative_rmse_pointwise_percent,
        "relative_rmse_mean_target_percent": relative_rmse_mean_target_percent,
        "mape_percent": mean_absolute_percentage_error,
        "mean_target_height": mean_target_height,
    }


def _format_metric_text(metrics: Dict[str, float]) -> str:
    return (
        f"relMSE(mean target) = {metrics['relative_mse_mean_target']:.6f}\n"
        f"relMSE(pointwise)   = {metrics['relative_mse_pointwise']:.6f}\n"
        f"% error (rRMSE mean target) = {metrics['relative_rmse_mean_target_percent']:.2f}%\n"
        f"% error (MAPE)             = {metrics['mape_percent']:.2f}%"
    )


def _add_metric_box(ax, metrics: Dict[str, float]) -> None:
    ax.text(
        0.02,
        0.98,
        _format_metric_text(metrics),
        transform=ax.transAxes,
        va="top",
        ha="left",
        fontsize=9,
        bbox=dict(boxstyle="round", facecolor="white", alpha=0.85, edgecolor="gray"),
    )


def compute_run_metrics(data: Dict[str, Any]) -> Dict[str, float]:
    final_height = data["heights"][-1]
    target = data["target"]
    err = final_height - target

    mse = float(np.mean(err ** 2))
    mae = float(np.mean(np.abs(err)))
    max_overshoot = float(np.max(np.maximum(err, 0.0)))
    max_deficit = float(np.max(np.maximum(-err, 0.0)))
    total_reward = float(np.sum(data["rewards"])) if len(data["rewards"]) else 0.0

    relative_metrics = _compute_relative_error_metrics(final_height=final_height, target=target)

    return {
        "mse": mse,
        "mae": mae,
        "max_overshoot": max_overshoot,
        "max_deficit": max_deficit,
        "total_reward": total_reward,
        **relative_metrics,
    }



def compute_relative_mse_mean_target(
    final_height: np.ndarray,
    target: np.ndarray,
    eps: float = 1e-12,
) -> float:
    # CHANGED:
    # Thêm helper đúng kiểu metric relative MSE theo mean(target)
    # để dùng cho plot GP amplitude vs relative MSE giống hình bạn gửi.
    err = final_height.astype(np.float64) - target.astype(np.float64)
    mse = float(np.mean(err ** 2))
    mean_target = float(np.mean(target.astype(np.float64)))
    denom = max(mean_target * mean_target, eps)
    return float(mse / denom)


def evaluate_gaussian_amplitude_robustness(
    model: PPO,
    venv: VecNormalize,
    cfg: ColdSpray1DConfig,
    amplitude_values: np.ndarray,
    eval_samples_per_amplitude: int,
    deterministic: bool,
) -> List[Dict[str, float]]:
    # CHANGED:
    # Evaluate nhiều amplitude cố định trong [0.01, 0.20].
    # Mỗi amplitude chạy nhiều sample để tạo thật nhiều chấm.
    if cfg.bump_type != "gaussian":
        raise ValueError("Robustness plot này chỉ dành cho bump_type='gaussian'.")

    rows: List[Dict[str, float]] = []
    for amp_idx, amp in enumerate(amplitude_values):
        for sample_idx in range(eval_samples_per_amplitude):
            reset_seed = 1000000 + amp_idx * 10000 + sample_idx
            data = rollout_model(
                model=model,
                venv=venv,
                cfg=cfg,
                deterministic=deterministic,
                reset_seed=reset_seed,
                forced_target_mod_relative_amplitude=float(amp),
            )
            rel_mse = compute_relative_mse_mean_target(
                final_height=data["heights"][-1],
                target=data["target"],
            )
            rows.append({
                "amplitude": float(amp),
                "amplitude_percent": float(100.0 * amp),
                "sample_idx": int(sample_idx),
                "reset_seed": int(reset_seed),
                "relative_mse": float(rel_mse),
                "sampled_target_mod_relative_amplitude": float(data["sampled_target_mod_relative_amplitude"]),
            })
    return rows


def summarize_gaussian_amplitude_robustness(rows: List[Dict[str, float]]) -> List[Dict[str, float]]:
    # CHANGED:
    # Gom theo amplitude để lấy mean/std/min/max cho errorbar plot.
    by_amp: Dict[float, List[float]] = {}
    for row in rows:
        by_amp.setdefault(float(row["amplitude"]), []).append(float(row["relative_mse"]))

    summary_rows: List[Dict[str, float]] = []
    for amp in sorted(by_amp.keys()):
        values = np.array(by_amp[amp], dtype=np.float64)
        summary_rows.append({
            "amplitude": float(amp),
            "amplitude_percent": float(100.0 * amp),
            "n": int(len(values)),
            "mean_relative_mse": float(np.mean(values)),
            "std_relative_mse": float(np.std(values)),
            "min_relative_mse": float(np.min(values)),
            "max_relative_mse": float(np.max(values)),
        })
    return summary_rows



            # Nếu không phải rect branch thì reset rect meta về 0.
            if self.cfg.bump_type != "rect":
                self.rect_amp = 0.0
                self.rect_width = 0.0
                self.rect_center = 0.0
                self.rect_bump_area = 0.0
                self.rect_normalized_severity = 0.0

            # ======================================================

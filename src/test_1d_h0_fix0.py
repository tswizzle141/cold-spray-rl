def evaluate_triangle_severity_robustness(
    model: PPO,
    venv: VecNormalize,
    cfg: ColdSpray1DConfig,
    severity_values: np.ndarray,
    eval_samples_per_severity: int,
    deterministic: bool,
) -> List[Dict[str, float]]:
    # ==========================================================
    # ADDED FOR TRIANGLE ROBUSTNESS PLOT:
    # Robustness plot cho bump_type='triangle'
    # - trục x: severity = triangle_area / (mean(target_base) * x_max)
    # - với triangle_area = 0.5 * amp * width
    # - trục y: relative MSE
    # ==========================================================
    if cfg.bump_type != "triangle":
        raise ValueError("Triangle severity plot này chỉ dành cho bump_type='triangle'.")

    rows: List[Dict[str, float]] = []
    for sev_idx, severity in enumerate(severity_values):
        for sample_idx in range(eval_samples_per_severity):
            reset_seed = 3000000 + sev_idx * 10000 + sample_idx
            data = rollout_model(
                model=model,
                venv=venv,
                cfg=cfg,
                deterministic=deterministic,
                reset_seed=reset_seed,
                forced_triangle_normalized_severity=float(severity),
            )
            rel_mse = compute_relative_mse_mean_target(
                final_height=data["heights"][-1],
                target=data["target"],
            )
            rows.append({
                "severity": float(severity),
                "severity_percent": float(100.0 * severity),
                "sample_idx": int(sample_idx),
                "reset_seed": int(reset_seed),
                "relative_mse": float(rel_mse),
                "tri_amp": float(data["tri_amp"]),
                "tri_width": float(data["tri_width"]),
                "tri_center": float(data["tri_center"]),
                "tri_bump_area": float(data["tri_bump_area"]),
                "tri_normalized_severity": float(data["tri_normalized_severity"]),
            })
    return rows



def _sample_rect_based_target_base_and_target(
    rng: np.random.Generator,
    x_grid: np.ndarray,
    cfg: ColdSpray1DConfig,
    dx: float,
    forced_rect_normalized_severity: Optional[float] = None,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, Dict[str, float]]:
    # ------------------------------------------------------------
    # (1) v_base_vec constant theo yêu cầu của bạn
    # ------------------------------------------------------------
    v_base_vec = np.full_like(x_grid, fill_value=cfg.base_v, dtype=np.float32)

    # ------------------------------------------------------------
    # (2) target_base sinh từ base_v constant
    #     target_base = feed_rate * dx / v_base
    #     => target_base cố định trên toàn miền
    # ------------------------------------------------------------
    target_base = (cfg.feed_rate * dx / np.maximum(v_base_vec, 1e-12)).astype(np.float32)

    # ------------------------------------------------------------
    # (3) Random rectangular bump shape
    #
    # CHANGED:
    # - nếu forced_rect_normalized_severity = None:
    #       sample amp, width như cũ
    # - nếu có giá trị severity:
    #       ép bump_area = severity * mean(target_base) * x_max
    #       sau đó chọn width khả thi, rồi suy ra amp = area / width
    #
    # Như vậy trục x của robustness plot là severity,
    # còn target_base vẫn cố định.
    # ------------------------------------------------------------
    if forced_rect_normalized_severity is None:
        amp = float(rng.uniform(cfg.rect_amp_min, cfg.rect_amp_max))
        width = float(rng.uniform(cfg.rect_width_min, cfg.rect_width_max))
        width = min(width, cfg.x_max)
    else:
        target_area = _compute_rect_bump_area_from_normalized_severity(
            normalized_severity=float(forced_rect_normalized_severity),
            target_base=target_base,
            x_max=cfg.x_max,
        )

        # width phải thỏa amp = area / width nằm trong [amp_min, amp_max]
        feasible_width_min = max(
            float(cfg.rect_width_min),
            float(target_area / max(cfg.rect_amp_max, 1e-12)),
        )
        feasible_width_max = min(
            float(cfg.rect_width_max),
            float(target_area / max(cfg.rect_amp_min, 1e-12)),
            float(cfg.x_max),
        )

        if feasible_width_min > feasible_width_max:
            raise ValueError(
                "Requested rect severity is infeasible with current rect amp/width ranges. "
                f"severity={forced_rect_normalized_severity}, "
                f"feasible_width_min={feasible_width_min}, feasible_width_max={feasible_width_max}"
            )

        width = float(rng.uniform(feasible_width_min, feasible_width_max))
        amp = float(target_area / max(width, 1e-12))

        # clip cực nhỏ do số học để tránh tràn biên vi mô
        amp = float(np.clip(amp, cfg.rect_amp_min, cfg.rect_amp_max))
        width = float(min(width, cfg.x_max))

    half_w = 0.5 * width
    center = float(rng.uniform(half_w, cfg.x_max - half_w)) if width < cfg.x_max else float(0.5 * cfg.x_max)

    target_modulation = _rectangular_bump(
        x_grid=x_grid,
        center=center,
        width=width,
        amp=amp,
    ).astype(np.float32)

    # ------------------------------------------------------------
    # (4) target_modified = target_base + rect bump
    # ------------------------------------------------------------
    target = np.maximum(target_base + target_modulation, 0.0).astype(np.float32)

    # ------------------------------------------------------------
    # (5) Tính meta để vẽ severity plot
    # ------------------------------------------------------------
    bump_area = _compute_rect_bump_area(amp=amp, width=width)
    rect_normalized_severity = _compute_rect_normalized_severity_from_area(
        bump_area=bump_area,
        target_base=target_base,
        x_max=cfg.x_max,
    )

    rect_meta = {
        "rect_amp": float(amp),
        "rect_width": float(width),
        "rect_center": float(center),
        "rect_bump_area": float(bump_area),
        "rect_normalized_severity": float(rect_normalized_severity),
    }

    # ------------------------------------------------------------
    # (6) Để giữ API return giống nhánh gaussian:
    #     - g_base = zeros vì mode rect không dùng GP cho base velocity
    #     - g_mod  = zeros vì mode rect không dùng GP modulation
    # ------------------------------------------------------------
    g_base = np.zeros_like(x_grid, dtype=np.float32)
    g_mod = np.zeros_like(x_grid, dtype=np.float32)

    return v_base_vec, target_base, target, target_modulation, g_base, g_mod, rect_meta


def _sample_circular_based_target_base_and_target(
    rng: np.random.Generator,
    x_grid: np.ndarray,
    cfg: ColdSpray1DConfig,
    dx: float,
    forced_circular_normalized_severity: Optional[float] = None,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, Dict[str, float]]:
    # ------------------------------------------------------------
    # CHANGED FOR CIRCULAR ROBUSTNESS PLOT:
    # Hỗ trợ 2 chế độ giống rect/triangle:
    # - random circular bump như cũ
    # - force circular severity để vẽ robustness plot
    # ------------------------------------------------------------
    v_base_vec = np.full_like(x_grid, fill_value=cfg.base_v, dtype=np.float32)
    target_base = (cfg.feed_rate * dx / np.maximum(v_base_vec, 1e-12)).astype(np.float32)

    if forced_circular_normalized_severity is None:
        amp = float(rng.uniform(cfg.circ_amp_min, cfg.circ_amp_max))
        width = float(rng.uniform(cfg.circ_width_min, cfg.circ_width_max))
        width = min(width, cfg.x_max)
    else:
        target_area = _compute_circular_bump_area_from_normalized_severity(
            normalized_severity=float(forced_circular_normalized_severity),
            target_base=target_base,
            x_max=cfg.x_max,
        )

        # circular_area = amp * pi * width / 4
        # => amp = 4 * area / (pi * width)
        feasible_width_min = max(
            float(cfg.circ_width_min),
            float(4.0 * target_area / (np.pi * max(cfg.circ_amp_max, 1e-12))),
        )
        feasible_width_max = min(
            float(cfg.circ_width_max),
            float(4.0 * target_area / (np.pi * max(cfg.circ_amp_min, 1e-12))),
            float(cfg.x_max),
        )

        if feasible_width_min > feasible_width_max:
            raise ValueError(
                "Requested circular severity is infeasible with current circular amp/width ranges. "
                f"severity={forced_circular_normalized_severity}, "
                f"feasible_width_min={feasible_width_min}, feasible_width_max={feasible_width_max}"
            )

        width = float(rng.uniform(feasible_width_min, feasible_width_max))
        amp = float(4.0 * target_area / (np.pi * max(width, 1e-12)))
        amp = float(np.clip(amp, cfg.circ_amp_min, cfg.circ_amp_max))
        width = float(min(width, cfg.x_max))

    half_w = 0.5 * width
    center = float(rng.uniform(half_w, cfg.x_max - half_w)) if width < cfg.x_max else float(0.5 * cfg.x_max)

    target_modulation = _circular_bump(
        x_grid=x_grid,
        center=center,
        width=width,
        amp=amp,
    ).astype(np.float32)

    target = np.maximum(target_base + target_modulation, 0.0).astype(np.float32)

    bump_area = _compute_circular_bump_area(amp=amp, width=width)
    circ_normalized_severity = _compute_circular_normalized_severity_from_area(
        bump_area=bump_area,
        target_base=target_base,
        x_max=cfg.x_max,
    )

    circ_meta = {
        "circ_amp": float(amp),
        "circ_width": float(width),
        "circ_center": float(center),
        "circ_bump_area": float(bump_area),
        "circ_normalized_severity": float(circ_normalized_severity),
    }

    g_base = np.zeros_like(x_grid, dtype=np.float32)
    g_mod = np.zeros_like(x_grid, dtype=np.float32)

    return v_base_vec, target_base, target, target_modulation, g_base, g_mod, circ_meta

def _sample_triangle_based_target_base_and_target(
    rng: np.random.Generator,
    x_grid: np.ndarray,
    cfg: ColdSpray1DConfig,
    dx: float,
    forced_triangle_normalized_severity: Optional[float] = None,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, Dict[str, float]]:

    # ==========================================================
    # ADDED FOR TRIANGLE ROBUSTNESS PLOT:
    # Hàm này được mở rộng để hỗ trợ 2 chế độ:
    # 1) random triangle như cũ
    # 2) force triangle severity khi cần vẽ robustness plot
    #
    # LƯU Ý:
    # - Không đụng logic rect / gaussian.
    # - Chỉ mở rộng riêng nhánh triangle.
    # ==========================================================

    # (1) base velocity constant
    v_base_vec = np.full_like(x_grid, fill_value=cfg.base_v, dtype=np.float32)

    # (2) base target
    target_base = (cfg.feed_rate * dx / np.maximum(v_base_vec, 1e-12)).astype(np.float32)

    # (3) random triangle params hoặc solve ngược từ severity
    if forced_triangle_normalized_severity is None:
        # ------------------------------------------------------
        # ADDED:
        # Giữ nguyên đúng behavior cũ:
        # nếu không force severity thì triangle vẫn random amp/width.
        # ------------------------------------------------------
        amp = float(rng.uniform(cfg.tri_amp_min, cfg.tri_amp_max))
        width = float(rng.uniform(cfg.tri_width_min, cfg.tri_width_max))
        width = min(width, cfg.x_max)
    else:
        # ------------------------------------------------------
        # ADDED:
        # Force triangle severity:
        #   triangle_area = severity * mean(target_base) * x_max
        # nhưng triangle_area = 0.5 * amp * width
        # => amp = 2 * area / width
        # ------------------------------------------------------
        target_area = _compute_triangle_bump_area_from_normalized_severity(
            normalized_severity=float(forced_triangle_normalized_severity),
            target_base=target_base,
            x_max=cfg.x_max,
        )

        feasible_width_min = max(
            float(cfg.tri_width_min),
            float(2.0 * target_area / max(cfg.tri_amp_max, 1e-12)),
        )
        feasible_width_max = min(
            float(cfg.tri_width_max),
            float(2.0 * target_area / max(cfg.tri_amp_min, 1e-12)),
            float(cfg.x_max),
        )

        if feasible_width_min > feasible_width_max:
            raise ValueError(
                "Requested triangle severity is infeasible with current triangle amp/width ranges. "
                f"severity={forced_triangle_normalized_severity}, "
                f"feasible_width_min={feasible_width_min}, feasible_width_max={feasible_width_max}"
            )

        width = float(rng.uniform(feasible_width_min, feasible_width_max))
        amp = float(2.0 * target_area / max(width, 1e-12))

        # ------------------------------------------------------
        # ADDED:
        # Clip cực nhỏ để tránh lệch số học ở sát biên.
        # ------------------------------------------------------
        amp = float(np.clip(amp, cfg.tri_amp_min, cfg.tri_amp_max))
        width = float(min(width, cfg.x_max))

    half_w = 0.5 * width
    center = (
        float(rng.uniform(half_w, cfg.x_max - half_w))
        if width < cfg.x_max
        else float(0.5 * cfg.x_max)
    )

    target_modulation = _triangular_bump(
        x_grid=x_grid,
        center=center,
        width=width,
        amp=amp,
    )

    # (4) final target
    target = np.maximum(target_base + target_modulation, 0.0).astype(np.float32)

    # ----------------------------------------------------------
    # ADDED:
    # Tính meta riêng cho triangle để export / debug / save json / plot.
    # ----------------------------------------------------------
    bump_area = _compute_triangle_bump_area(amp=amp, width=width)
    tri_normalized_severity = _compute_triangle_normalized_severity_from_area(
        bump_area=bump_area,
        target_base=target_base,
        x_max=cfg.x_max,
    )

    tri_meta = {
        "tri_amp": float(amp),
        "tri_width": float(width),
        "tri_center": float(center),
        "tri_bump_area": float(bump_area),
        "tri_normalized_severity": float(tri_normalized_severity),
    }

    # (5) giữ API
    g_base = np.zeros_like(x_grid, dtype=np.float32)
    g_mod = np.zeros_like(x_grid, dtype=np.float32)

    return v_base_vec, target_base, target, target_modulation, g_base, g_mod, tri_meta


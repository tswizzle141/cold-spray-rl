def main() -> None:
    out_dir = ensure_output_dir()

    cfg_original = ColdSpray1DConfig(use_geometry_dependent_kernel=False)
    cfg_modified = ColdSpray1DConfig(
        use_geometry_dependent_kernel=True,
        use_sod_dependent_kernel=USE_SOD_IN_MODIFIED_KERNEL,
    )

    print("[INFO] Output directory:", out_dir)
    print("[INFO] Target mode:", TARGET_MODE)
    print("[INFO] Object region:", (X_START, X_END), "approx final mean height =", N_LAYERS * LAYER_THICKNESS)
    print("[INFO] Layers:", N_LAYERS, "x", LAYER_THICKNESS)
    print("[INFO] Modified kernel uses geometry:", cfg_modified.use_geometry_dependent_kernel)
    print("[INFO] Modified kernel uses SOD:", cfg_modified.use_sod_dependent_kernel)

    modified_model = None
    modified_vecnorm = None

    if USE_TRAINED_AGENTS:
        # Thesis 3-case comparison (matching the three reference figures):
        #   A) Slicer / original   : v = v_base,                 K_execution = K_sigma
        #   B) Slicer / modified   : v = v_base,                 K_execution = K_modified
        #   C) RL / modified       : v = v_base + delta_v,       K_execution = K_modified
        modified_model = load_ppo(MODIFIED_MODEL_ZIP)
        modified_vecnorm = load_vecnormalize(MODIFIED_VECNORMALIZE_PKL, cfg_modified)

    cases = [
        CaseSpec(
            name="Case A: slicer-only executed with original Gaussian kernel",
            short_name="Slicer / original",
            cfg=cfg_original,
            use_agent=False,
        ),
    ]

    cases.append(
        CaseSpec(
            name="Case B: slicer-only executed with modified geometry-dependent kernel",
            short_name="Slicer / modified",
            cfg=cfg_modified,
            use_agent=False,
        )
    )

    if USE_TRAINED_AGENTS and modified_model is not None:
        cases.append(
            CaseSpec(
                name="Case C: trained PPO correction executed with modified geometry-dependent kernel",
                short_name="RL / modified",
                cfg=cfg_modified,
                model=modified_model,
                vecnorm=modified_vecnorm,
                use_agent=True,
            )
        )
    else:
        print("[WARN] Modified trained PPO is not available, so RL / modified is skipped.")

    # CHANGED: optionally select a hard target shape automatically.
    # This is useful because the desired claim depends on the actual PPO weights.
    if AUTO_SELECT_SHAPE and USE_TRAINED_AGENTS and modified_model is not None:
        selected_mode, selected_amp, results, search_rows = select_best_shape_by_rel_mse(cases, out_dir)
        print(f"[INFO] Using selected target: {selected_mode} with amplitude {selected_amp}")
    else:
        results = [simulate_case(case, eval_seed=EVAL_SEED) for case in cases]

    print_final_table(results)

    json_path = save_summary_json(results, out_dir)
    fig0 = plot_target_shape(out_dir)
    fig1 = plot_prof_summary(results, out_dir)
    fig2 = plot_selected_layer_snapshots(results, out_dir)
    fig3 = plot_velocity_heatmaps(results, out_dir)
    fig4 = plot_velocity_corrections(results, out_dir)

    print("[SAVED]")
    print(" metrics:", json_path)
    print(" figure :", fig0)
    print(" figure :", fig1)
    print(" figure :", fig2)
    print(" figure :", fig3)
    print(" figure :", fig4)


if __name__ == "__main__":
    main()
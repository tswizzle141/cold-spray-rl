def gaussian_kernel_discrete(
    x_grid: np.ndarray,
    center: float,
    sigma: float,
    dx: float,
) -> np.ndarray:
    """
    Discrete nominal Gaussian kernel.

    K_i = K_sigma(x_i - center) * dx, so sum_i K_i is approximately one.
    """
    z = (x_grid - float(center)) / max(float(sigma), 1e-12)
    w = np.exp(-0.5 * z * z) / (float(sigma) * math.sqrt(2.0 * math.pi))
    return (w * float(dx)).astype(np.float32)


def smooth_1d_reflect(y: np.ndarray, window: int) -> np.ndarray:
    window = int(window)
    if window <= 1:
        return y.astype(np.float32, copy=True)
    if window % 2 == 0:
        window += 1
    pad = window // 2
    y_pad = np.pad(y.astype(np.float64), pad_width=pad, mode="reflect")
    kernel = np.ones(window, dtype=np.float64) / float(window)
    return np.convolve(y_pad, kernel, mode="valid").astype(np.float32)


def surface_slope(height: np.ndarray, dx: float, smoothing_window: int) -> np.ndarray:
    h_smooth = smooth_1d_reflect(height, smoothing_window)
    return np.gradient(h_smooth.astype(np.float64), float(dx)).astype(np.float32)


def geometry_efficiency_from_slope(slope: np.ndarray, p: float) -> np.ndarray:
    """eta_geom(m) = (1 + m^2)^(-p/2)."""
    m = slope.astype(np.float64)
    eta = np.power(1.0 + m * m, -0.5 * float(p))
    return eta.astype(np.float32)


def sod_efficiency_from_height(
    height: np.ndarray,
    nominal_standoff_distance: float,
    sod_optimal_distance: float,
    sod_sigma: float,
    sod_eta_min: float,
) -> np.ndarray:
    """Optional SOD factor for future experiments."""
    sigma_d = max(float(sod_sigma), 1e-12)
    eta_min = float(np.clip(sod_eta_min, 0.0, 1.0))
    d_local = float(nominal_standoff_distance) - height.astype(np.float64)
    z = (d_local - float(sod_optimal_distance)) / sigma_d
    eta = eta_min + (1.0 - eta_min) * np.exp(-0.5 * z * z)
    return np.clip(eta, eta_min, 1.0).astype(np.float32)


def execution_kernel(
    x_grid: np.ndarray,
    center: float,
    height_for_geometry: np.ndarray,
    cfg: ColdSpray1DConfig,
    dx: float,
) -> np.ndarray:
    """
    Original:
        K_exec = K_sigma

    Modified:
        K_exec = eta_geom(dh/dx) * K_sigma

    Optional SOD:
        K_exec = eta_geom(dh/dx) * eta_sod(d) * K_sigma

    The Gaussian footprint is not widened and is not re-normalized.
    """
    k = gaussian_kernel_discrete(x_grid, center, cfg.sigma, dx)

    if not cfg.use_geometry_dependent_kernel:
        return k

    slope = surface_slope(height_for_geometry, dx, cfg.slope_smoothing_window)
    eta_geom = geometry_efficiency_from_slope(slope, cfg.geometry_kernel_p)

    if cfg.use_sod_dependent_kernel:
        eta_sod = sod_efficiency_from_height(
            height=height_for_geometry,
            nominal_standoff_distance=cfg.nominal_standoff_distance,
            sod_optimal_distance=cfg.sod_optimal_distance,
            sod_sigma=cfg.sod_sigma,
            sod_eta_min=cfg.sod_eta_min,
        )
    else:
        eta_sod = np.ones_like(k, dtype=np.float32)

    return (eta_geom * eta_sod * k).astype(np.float32)


def profile_metrics(height: np.ndarray, target: np.ndarray) -> Dict[str, float]:
    h = height.astype(np.float64)
    t = target.astype(np.float64)
    err = h - t
    ov = np.maximum(err, 0.0)
    uf = np.maximum(-err, 0.0)
    mse = float(np.mean(err ** 2))
    mean_t = float(np.mean(np.abs(t)))
    rel_mse = mse / max(mean_t * mean_t, 1e-12)
    return {
        "mse": mse,
        "rel_mse": rel_mse,
        "mae": float(np.mean(np.abs(err))),
        "max_abs_error": float(np.max(np.abs(err))),
        "max_overshoot": float(np.max(ov)),
        "mean_overshoot": float(np.mean(ov)),
        "max_underfill": float(np.max(uf)),
        "mean_underfill": float(np.mean(uf)),
    }



def build_x_grid(cfg: ColdSpray1DConfig) -> Tuple[np.ndarray, float, float]:
    x_grid = np.linspace(0.0, cfg.x_max, cfg.n_bins, dtype=np.float32)
    dx = float(x_grid[1] - x_grid[0])
    ds = float(cfg.x_max / cfg.n_steps)
    return x_grid, dx, ds


def layer_increment_target(x_grid: np.ndarray) -> np.ndarray:
    """
    CHANGED HARD-SHAPE TARGET GENERATOR.

    The old rectangle target is kept as a sanity check, but the default target
    is now "hard_double_bump".  The reason is important for the mentor demo:

        rectangle  -> slicer/original is almost perfect; no correction needed.
        hard shape -> stronger slopes and local curvature; the modified
                      geometry-dependent execution kernel creates visible
                      mismatch; RL correction has something meaningful to fix.

    We build a one-layer target increment Delta h(x), then normalize its mean
    over the active region to LAYER_THICKNESS.  Therefore after 10 layers the
    average final height is still approximately 0.2.
    """
    left = min(float(X_START), float(X_END))
    right = max(float(X_START), float(X_END))
    mask = (x_grid >= left) & (x_grid <= right)

    target = np.zeros_like(x_grid, dtype=np.float32)
    x = x_grid.astype(np.float64)

    # Helper: normalize any positive raw profile so that mean over the active
    # print region equals LAYER_THICKNESS.  This keeps all target modes
    # comparable in total deposited material.
    def _normalize_increment(raw: np.ndarray) -> np.ndarray:
        raw = np.asarray(raw, dtype=np.float64)
        raw = np.maximum(raw, 1e-4)
        active_mean = float(np.mean(raw[mask])) if np.any(mask) else float(np.mean(raw))
        return raw * (float(LAYER_THICKNESS) / max(active_mean, 1e-12))

    if TARGET_MODE == "rectangle":
        raw = np.full_like(x, float(LAYER_THICKNESS), dtype=np.float64)

    elif TARGET_MODE == "sine":
        # Smooth single-frequency target. Moderate difficulty.
        raw = float(LAYER_THICKNESS) + float(TARGET_AMPLITUDE) * np.sin(2.0 * np.pi * x)

    elif TARGET_MODE == "bump":
        # One centered Gaussian bump. Good simple local feature.
        bump = np.exp(-0.5 * ((x - 0.50) / max(float(BUMP_SIGMA), 1e-12)) ** 2)
        raw = float(LAYER_THICKNESS) + float(TARGET_AMPLITUDE) * bump

    elif TARGET_MODE == "hard_double_bump":
        # CHANGED DEFAULT:
        # Two asymmetric bumps with different widths, plus a shallow valley.
        # This creates local slopes and curvature while staying smooth enough
        # for a Gaussian deposition model.  It is harder than sine and better
        # for showing geometry-dependent model mismatch.
        bump1 = np.exp(-0.5 * ((x - 0.28) / 0.075) ** 2)
        bump2 = 0.75 * np.exp(-0.5 * ((x - 0.72) / 0.120) ** 2)
        valley = 0.45 * np.exp(-0.5 * ((x - 0.50) / 0.110) ** 2)
        raw = float(LAYER_THICKNESS) + float(TARGET_AMPLITUDE) * (bump1 + bump2 - valley)

    elif TARGET_MODE == "sharp_double_peak":
        # CHANGED: hard target intended to make the pointwise slicer less ideal.
        # Two narrow smooth peaks plus a small valley create high local curvature.
        # Because the slicer uses a very simple local inverse while execution is
        # a convolution with a finite Gaussian footprint, this target can produce
        # visible model/planning error even for Slicer/original.
        peak1 = 1.00 * np.exp(-0.5 * ((x - 0.27) / 0.040) ** 2)
        peak2 = 0.85 * np.exp(-0.5 * ((x - 0.68) / 0.050) ** 2)
        valley = 0.55 * np.exp(-0.5 * ((x - 0.48) / 0.080) ** 2)
        raw = float(LAYER_THICKNESS) + float(TARGET_AMPLITUDE) * (peak1 + peak2 - valley)

    elif TARGET_MODE == "edge_peak":
        # CHANGED: a narrow feature near the boundary.
        # Boundary effects are difficult for a Gaussian footprint and can make
        # Slicer/original less perfect, while the RL correction may compensate
        # by changing velocity locally.
        peak = 1.15 * np.exp(-0.5 * ((x - 0.88) / 0.045) ** 2)
        shoulder = 0.45 * np.exp(-0.5 * ((x - 0.34) / 0.130) ** 2)
        valley = 0.35 * np.exp(-0.5 * ((x - 0.62) / 0.090) ** 2)
        raw = float(LAYER_THICKNESS) + float(TARGET_AMPLITUDE) * (peak + shoulder - valley)

    elif TARGET_MODE == "smooth_cliff_peak":
        # CHANGED: smooth step + local peak.
        # This creates a high-slope transition region without using a
        # discontinuous, physically unrealistic hard step.
        step = np.tanh(float(SMOOTH_STEP_K) * (x - 0.54))
        peak = np.exp(-0.5 * ((x - 0.30) / 0.055) ** 2)
        raw = float(LAYER_THICKNESS) + float(TARGET_AMPLITUDE) * (0.50 * step + 0.90 * peak)

    elif TARGET_MODE == "high_curvature_wave":
        # CHANGED: deterministic multi-frequency wave.
        # Compared with a simple sine, this has higher curvature and several
        # local extrema, which makes the pointwise slicer less accurate.
        raw = (
            float(LAYER_THICKNESS)
            + float(TARGET_AMPLITUDE) * (
                0.75 * np.sin(2.0 * np.pi * x + 0.20)
                + 0.45 * np.sin(6.0 * np.pi * x - 0.60)
                + 0.25 * np.cos(10.0 * np.pi * x + 0.90)
            )
        )

    elif TARGET_MODE == "edge_bump":
        # A bump close to the right boundary. This is useful because boundary
        # effects plus local slope often make slicer-only execution worse.
        bump = np.exp(-0.5 * ((x - 0.83) / 0.070) ** 2)
        shoulder = 0.55 * np.exp(-0.5 * ((x - 0.35) / 0.16) ** 2)
        raw = float(LAYER_THICKNESS) + float(TARGET_AMPLITUDE) * (bump + 0.4 * shoulder)

    elif TARGET_MODE == "ramp":
        # Global inclined layer. Useful for testing slope-dependent deposition.
        raw = float(LAYER_THICKNESS) + float(TARGET_AMPLITUDE) * (x - 0.5)

    elif TARGET_MODE == "smooth_step":
        # Smooth low-to-high transition. This is more physical than a hard step
        # and creates a localized high-slope transition region.
        step = 1.0 / (1.0 + np.exp(-float(SMOOTH_STEP_K) * (x - 0.52)))
        raw = float(LAYER_THICKNESS) + float(TARGET_AMPLITUDE) * (step - np.mean(step[mask]))

    elif TARGET_MODE == "gp_like":
        # Deterministic smooth GP-like target: mixture of low-frequency modes.
        # This is useful as a robustness target without using random sampling.
        raw = (
            float(LAYER_THICKNESS)
            + float(TARGET_AMPLITUDE) * (
                0.75 * np.sin(2.0 * np.pi * x + 0.30)
                + 0.40 * np.sin(4.0 * np.pi * x - 0.80)
                + 0.25 * np.cos(6.0 * np.pi * x + 0.50)
            )
        )

    else:
        raise ValueError(
            f"Unknown TARGET_MODE={TARGET_MODE!r}. Use 'rectangle', 'sine', 'bump', "
            f"'hard_double_bump', 'edge_bump', 'ramp', 'smooth_step', or 'gp_like'."
        )

    inc = _normalize_increment(raw)
    target[mask] = inc[mask].astype(np.float32)
    return target


def cumulative_target(x_grid: np.ndarray, layer_index: int) -> np.ndarray:
    return float(layer_index) * layer_increment_target(x_grid)


def slicer_base_velocity_profile(
    x_grid: np.ndarray,
    layer_target_increment: np.ndarray,
    cfg: ColdSpray1DConfig,
    dx: float,
) -> np.ndarray:
    """
    Simple nominal slicer velocity profile.

    The nominal relation from the training setup is approximately:
        desired_increment(x) = feed_rate * dx / v_base(x)

    Hence:
        v_base(x) = feed_rate * dx / desired_increment(x)

    Outside the object region the simplified model has no spray on/off command,
    so the slicer uses maximum velocity to minimize unwanted deposition.
    """
    eps = 1e-12
    v = np.full_like(x_grid, fill_value=float(cfg.v_max), dtype=np.float32)
    mask = layer_target_increment > eps
    v[mask] = float(cfg.feed_rate) * float(dx) / np.maximum(layer_target_increment[mask], eps)
    return np.clip(v, cfg.v_min, cfg.v_max).astype(np.float32)


def x_to_idx(x_grid: np.ndarray, x: float) -> int:
    return int(np.clip(np.searchsorted(x_grid, x, side="left"), 0, len(x_grid) - 1))


def value_at_x(x_grid: np.ndarray, values: np.ndarray, x: float) -> float:
    return float(values[x_to_idx(x_grid, x)])


def make_policy_observation(
    layer_height: np.ndarray,
    layer_target_increment: np.ndarray,
    x_norm: float,
    velocity: float,
    local_base_v: float,
) -> np.ndarray:
    """
    Observation for trained 1D PPO policies.

    For layer-by-layer application, the policy sees the current layer in local
    coordinates:
        layer_height = global_height - height_at_start_of_current_layer

    This avoids feeding cumulative heights up to 0.2 into a policy trained on
    one-layer profiles around 0.02. The physical kernel is still evaluated on
    the global height profile.
    """
    delta = (layer_height - layer_target_increment).astype(np.float32)
    remaining = np.float32(1.0 - x_norm)
    obs = np.concatenate(
        [
            layer_height.astype(np.float32),
            delta,
            np.array([x_norm, remaining, velocity, local_base_v], dtype=np.float32),
        ],
        axis=0,
    )
    return obs.astype(np.float32)



class DummyColdSprayBoxEnv(gym.Env):
    """
    Dummy environment with the same observation shape as the 1D training files:
        [height(256), height-target(256), x_norm, remaining, velocity, local_base_v]
        dimension = 2*n_bins + 4 = 516.
    """
    metadata = {"render_modes": []}

    def __init__(self, cfg: ColdSpray1DConfig):
        super().__init__()
        obs_dim = 2 * int(cfg.n_bins) + 4
        self.observation_space = spaces.Box(
            low=-np.inf,
            high=np.inf,
            shape=(obs_dim,),
            dtype=np.float32,
        )
        self.action_space = spaces.Box(
            low=np.array([-1.0], dtype=np.float32),
            high=np.array([1.0], dtype=np.float32),
            dtype=np.float32,
        )

    def reset(self, seed: Optional[int] = None, options: Optional[dict] = None):
        return np.zeros(self.observation_space.shape, dtype=np.float32), {}

    def step(self, action):
        obs = np.zeros(self.observation_space.shape, dtype=np.float32)
        return obs, 0.0, False, True, {}


def make_dummy_vec_env(cfg: ColdSpray1DConfig) -> DummyVecEnv:
    return DummyVecEnv([lambda: Monitor(DummyColdSprayBoxEnv(cfg))])


def load_vecnormalize(path: str, cfg: ColdSpray1DConfig) -> Optional[VecNormalize]:
    p = Path(path)
    if not p.exists():
        print(f"[WARN] VecNormalize not found: {p}")
        return None
    dummy = make_dummy_vec_env(cfg)
    vec = VecNormalize.load(str(p), dummy)
    vec.training = False
    vec.norm_reward = False
    print(f"[OK] Loaded VecNormalize: {p}")
    return vec


def load_ppo(path: str) -> Optional[PPO]:
    p = Path(path)
    if not p.exists():
        print(f"[WARN] PPO model not found: {p}")
        return None
    model = PPO.load(str(p), device="cpu")
    print(f"[OK] Loaded PPO model: {p}")
    return model


def normalize_obs(obs: np.ndarray, vecnorm: Optional[VecNormalize]) -> np.ndarray:
    obs_batch = obs[None, :].astype(np.float32)
    if vecnorm is None:
        return obs_batch
    return vecnorm.normalize_obs(obs_batch)



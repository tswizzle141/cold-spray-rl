def simulate_case(case: CaseSpec, eval_seed: int = EVAL_SEED) -> Dict[str, Any]:
    _ = np.random.default_rng(eval_seed)  # reserved for future noise switches

    cfg = case.cfg
    x_grid, dx, ds = build_x_grid(cfg)

    height = np.zeros_like(x_grid, dtype=np.float32)
    one_layer_target = layer_increment_target(x_grid)

    layer_heights: List[np.ndarray] = []
    layer_targets: List[np.ndarray] = []
    layer_metrics: List[Dict[str, float]] = []
    all_velocities: List[List[float]] = []
    all_actions: List[List[float]] = []
    # CHANGED: store what the agent actually does.
    # v_base comes from the slicer, dv is the RL correction, and v = v_base + dv.
    all_base_velocities: List[List[float]] = []
    all_dvs: List[List[float]] = []
    # CHANGED: adaptive slicer. Store the full v_base profile planned at the
    # beginning of each layer, because v_base is no longer the same for all layers.
    all_v_base_profiles: List[np.ndarray] = []
    all_desired_layer_increments: List[np.ndarray] = []

    for layer in range(1, N_LAYERS + 1):
        h_start_layer = height.copy()

        # CHANGED: adaptive slicer planning is done ONCE PER LAYER.
        # The old code computed
        #     v_base_vec = slicer_base_velocity_profile(one_layer_target)
        # once before the layer loop and reused it for all layers.
        # Now the slicer looks at the current accumulated height at the start
        # of this layer and asks: "how much material is still needed to reach
        # the cumulative target after this layer?"
        #
        # target_after_layer(x) = layer * Delta h_target(x)
        # desired_increment_this_layer(x) = target_after_layer(x) - h_start_layer(x)
        # Negative values mean the point is already overfilled, so the slicer
        # requests zero additional material there, which maps to v_max.
        target_after_layer = cumulative_target(x_grid, layer)
        desired_increment_this_layer = np.maximum(
            target_after_layer.astype(np.float32) - h_start_layer.astype(np.float32),
            0.0,
        ).astype(np.float32)

        # CHANGED: v_base_vec is now recomputed for this layer only.
        v_base_vec = slicer_base_velocity_profile(
            x_grid=x_grid,
            layer_target_increment=desired_increment_this_layer,
            cfg=cfg,
            dx=dx,
        )
        all_v_base_profiles.append(v_base_vec.copy())
        all_desired_layer_increments.append(desired_increment_this_layer.copy())

        velocities_this_layer: List[float] = []
        actions_this_layer: List[float] = []
        base_velocities_this_layer: List[float] = []
        dvs_this_layer: List[float] = []

        nozzle_x = 0.0
        prev_velocity = value_at_x(x_grid, v_base_vec, 0.0)

        for _step in range(cfg.n_steps):
            x_prev = nozzle_x
            ds_eff = float(min(ds, cfg.x_max - nozzle_x))
            x_next = float(min(cfg.x_max, nozzle_x + ds_eff))

            x_mid = x_prev + 0.5 * ds_eff
            x_norm = np.float32(x_prev / cfg.x_max)
            local_base_v = value_at_x(x_grid, v_base_vec, x_mid)

            if case.use_agent and case.model is not None:
                layer_height = (height - h_start_layer).astype(np.float32)
                obs = make_policy_observation(
                    layer_height=layer_height,
                    # CHANGED: the policy receives the adaptive per-layer
                    # target increment, not the fixed nominal one_layer_target.
                    layer_target_increment=desired_increment_this_layer,
                    x_norm=float(x_norm),
                    velocity=float(prev_velocity),
                    local_base_v=float(local_base_v),
                )
                obs_model = normalize_obs(obs, case.vecnorm)
                action, _ = case.model.predict(obs_model, deterministic=DETERMINISTIC_ACTION)
                action_scalar = float(np.asarray(action).reshape(-1)[0])
                dv = float(np.clip(action_scalar, -1.0, 1.0)) * cfg.delta_v_max
            else:
                action_scalar = 0.0
                dv = 0.0

            v = float(np.clip(local_base_v + dv, cfg.v_min, cfg.v_max))
            velocities_this_layer.append(v)
            actions_this_layer.append(action_scalar)
            # CHANGED: log adaptive slicer velocity and RL velocity correction.
            base_velocities_this_layer.append(float(local_base_v))
            dvs_this_layer.append(float(dv))

            # Average a few kernel samples inside the segment, following the training-file style.
            L = ds_eff
            n_q = max(2, int(np.ceil(L / dx))) if L > 0.0 else 2
            h_old_for_kernel = height.copy()
            k_acc = np.zeros_like(height, dtype=np.float32)

            for j in range(n_q):
                s_j = (j + 0.5) * L / n_q
                x_j = x_prev + s_j
                k_acc += execution_kernel(
                    x_grid=x_grid,
                    center=x_j,
                    height_for_geometry=h_old_for_kernel,
                    cfg=cfg,
                    dx=dx,
                )

            k_seg = k_acc / float(n_q)
            dt_step = ds_eff / max(v, 1e-12)
            m_step = cfg.feed_rate * dt_step
            height = (height + (m_step * k_seg).astype(np.float32)).astype(np.float32)

            nozzle_x = x_next
            prev_velocity = v

        layer_heights.append(height.copy())
        layer_targets.append(target_after_layer.copy())
        layer_metrics.append(profile_metrics(height, target_after_layer))
        all_velocities.append(velocities_this_layer)
        all_actions.append(actions_this_layer)
        all_base_velocities.append(base_velocities_this_layer)
        all_dvs.append(dvs_this_layer)

    final_target = cumulative_target(x_grid, N_LAYERS)
    return {
        "name": case.name,
        "short_name": case.short_name,
        "cfg": asdict(cfg),
        "kernel_mode": "modified" if cfg.use_geometry_dependent_kernel else "original",
        "uses_sod": bool(cfg.use_sod_dependent_kernel),
        "use_agent": bool(case.use_agent and case.model is not None),
        "x_grid": x_grid,
        "one_layer_target": one_layer_target,
        # CHANGED: old scripts expected v_base_vec. Keep a backward-compatible
        # representative profile, but the real adaptive data is v_base_profiles.
        "v_base_vec": all_v_base_profiles[0].copy(),
        "v_base_profiles": np.stack(all_v_base_profiles, axis=0),
        "desired_layer_increments": np.stack(all_desired_layer_increments, axis=0),
        "layer_heights": np.stack(layer_heights, axis=0),
        "layer_targets": np.stack(layer_targets, axis=0),
        "layer_metrics": layer_metrics,
        "velocities": np.array(all_velocities, dtype=np.float32),
        "actions": np.array(all_actions, dtype=np.float32),
        # CHANGED: these arrays are needed to answer the mentor's question
        # "what does the agent actually do?"
        "base_velocities": np.array(all_base_velocities, dtype=np.float32),
        "dvs": np.array(all_dvs, dtype=np.float32),
        "final_height": layer_heights[-1],
        "final_target": final_target,
        "final_metrics": profile_metrics(layer_heights[-1], final_target),
    }



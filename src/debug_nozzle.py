    obs, _ = env.reset()

    action = np.array([1e-12, 0.0], dtype=np.float32)  # dx = 0.05
    x0, y0 = env.x, env.y
    x1, y1 = x0 + action[0], y0 + action[1]

    f = 0.1
    dt = cfg_test.dt

    M_in = cfg_test.eta * f * dt
    print("M_in (physical) =", M_in)

    delta_h = env.deposition.apply(env.height, x0, y0, x1, y1, f, dt)

    pix_area = (1.0 / cfg_test.grid_n) ** 2
    M_out = np.sum(delta_h * cfg_test.rho_m * pix_area)

    print("M_out (from height-map) =", M_out)
    print("Ratio M_out / M_in =", M_out / M_in)

    #CASE 2: REMOVE C (NON-NORMALIZED KERNEL)
    print("\n--- CASE 2: KERNEL WITHOUT C (REMOVE NORMALIZATION) ---")

    #shut C off
    orig_kernel = env.deposition._kernel

    def kernel_no_C(r):
        # same as original kernel but WITHOUT self._C
        return env.deposition.A_amp * np.exp(-(r/env.deposition.sigma)**env.deposition.beta)

    env.deposition._kernel = kernel_no_C

    delta_h2 = env.deposition.apply(env.height*0, x0, y0, x1, y1, f, dt)
    M_out2 = np.sum(delta_h2 * cfg_test.rho_m * pix_area)

    print("M_out_noC (from height-map) =", M_out2)
    print("Ratio M_out_noC / M_in =", M_out2 / M_in)

    # restore kernel to avoid side effects
    env.deposition._kernel = orig_kernel
    print("\nDone.")


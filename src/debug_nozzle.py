class ColdSprayConfig:
    grid_n: int = 128
    dx_max: float = 0.1
    dy_max: float = 0.1
    #df_max: float = 0.1
    dt: float = 0.05
    max_steps: int = 4000
    seed: Optional[int] = None

    sigma: float = 0.02
    beta: float = 2.0
    eta: float = 0.4

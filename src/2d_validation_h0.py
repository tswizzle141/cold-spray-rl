def load_checkpoint_compatible_model(model_path: Path) -> PPO:
    """
    Load a checkpoint with the exact feature-extractor layout in its weights.

    Some model-12 checkpoints were saved with ``share_features_extractor=False``
    even though later copies of the training script omitted that flag.  In that
    case SB3 otherwise rebuilds a parameter-free CombinedExtractor, flattens
    map+state to 2053 values, and then fails to load the 160-feature checkpoint.

    This loader inspects only the checkpoint metadata/state-dict keys.  It does
    not silently discard incompatible weights and never uses ``strict=False``.
    """
    device = "cuda" if torch.cuda.is_available() else "cpu"
    data, params, _ = load_from_zip_file(
        str(model_path),
        device=device,
        custom_objects=None,
        print_system_info=False,
    )
    if data is None or params is None or "policy" not in params:
        raise RuntimeError(f"Invalid PPO checkpoint: {model_path}")

    policy_state = params["policy"]
    state_keys = tuple(policy_state.keys())
    has_custom_extractor_weights = any(".map_cnn." in key for key in state_keys)
    has_separate_extractors = any(
        key.startswith(("pi_features_extractor.", "vf_features_extractor."))
        for key in state_keys
    )

    saved_policy_kwargs = dict(data.get("policy_kwargs") or {})
    if has_custom_extractor_weights:
        # Preserve every other saved option (net_arch, activation_fn, etc.) and
        # repair only the extractor fields that must match the state dict.
        saved_policy_kwargs["features_extractor_class"] = ColdSpray2DMultiInputExtractor
        saved_policy_kwargs["features_extractor_kwargs"] = {
            "cnn_output_dim": 128,
            "state_output_dim": 32,
        }
        saved_policy_kwargs["share_features_extractor"] = not has_separate_extractors

    load_kwargs = {
        "env": None,
        "device": device,
        "custom_objects": {"policy_kwargs": saved_policy_kwargs},
    }

    try:
        model = PPO.load(str(model_path), **load_kwargs)
    except ValueError as exc:
        # A PPO zip also stores Adam's training-only momentum/variance buffers.
        # Reconstructing an old custom policy can legitimately change Adam's
        # parameter-group bookkeeping even when every policy tensor is an exact
        # match.  Optimizer state is never used by model.predict(), so retry the
        # inference load while suppressing only Optimizer.load_state_dict().
        #
        # Importantly, nn.Module.load_state_dict() is NOT patched: all feature
        # extractor, actor and critic weights are still checked strictly by SB3.
        optimizer_group_mismatch = (
            "loaded state dict contains a parameter group" in str(exc)
            and "optimizer's group" in str(exc)
        )
        if not optimizer_group_mismatch:
            raise
        print(
            "Checkpoint policy is compatible, but its saved Adam parameter "
            "groups are training-only and incompatible. Loading for inference "
            "without optimizer state."
        )
        with patch.object(torch.optim.Optimizer, "load_state_dict", return_value=None):
            model = PPO.load(str(model_path), **load_kwargs)
    except RuntimeError as exc:
        key_summary = (
            f"custom_extractor={has_custom_extractor_weights}, "
            f"separate_actor_critic_extractors={has_separate_extractors}"
        )
        raise RuntimeError(
            "The PPO checkpoint still does not match the reconstructed model "
            f"({key_summary}). Make sure {model_path.name} and "
            "its corresponding VecNormalize file came from the same training run. "
            "Original SB3 error follows:\n"
            f"{exc}"
        ) from exc

    expected_dim = 160
    first_pi_layer = model.policy.mlp_extractor.policy_net[0]
    first_vf_layer = model.policy.mlp_extractor.value_net[0]
    if (
        not isinstance(first_pi_layer, nn.Linear)
        or not isinstance(first_vf_layer, nn.Linear)
        or first_pi_layer.in_features != expected_dim
        or first_vf_layer.in_features != expected_dim
    ):
        raise RuntimeError(
            "Checkpoint was loaded with the wrong latent feature size: "
            f"policy={getattr(first_pi_layer, 'in_features', None)}, "
            f"value={getattr(first_vf_layer, 'in_features', None)}, "
            f"expected={expected_dim}."
        )

    print(
        "Loaded PPO checkpoint successfully: "
        f"160 features, share_features_extractor={not has_separate_extractors}"
    )
    return model


def validate_normalizer_compatibility(
    model: PPO,
    normalizer: VecNormalize,
) -> None:
    """Fail early when the model and VecNormalize files are not a matching pair."""
    model_space = model.observation_space
    norm_space = normalizer.observation_space
    if not isinstance(model_space, spaces.Dict) or not isinstance(norm_space, spaces.Dict):
        raise RuntimeError("The model requires Dict observations with keys 'map' and 'state'.")
    if set(model_space.spaces) != {"map", "state"}:
        raise RuntimeError(
            f"Unexpected model observation keys: {sorted(model_space.spaces)}"
        )
    for key in ("map", "state"):
        model_shape = model_space[key].shape
        norm_shape = norm_space[key].shape
        if model_shape != norm_shape:
            raise RuntimeError(
                f"Observation shape mismatch for '{key}': "
                f"model={model_shape}, VecNormalize={norm_shape}. "
                "Use the VecNormalize file saved together with this checkpoint."
            )


def batched(obs: Dict[str, np.ndarray]) -> Dict[str, np.ndarray]:
    return {key: value[None, ...].astype(np.float32) for key, value in obs.items()}


def run_rollout(
    cfg: ColdSpray2DConfig,
    bundle: GPTarget2DBundle,
    model: Optional[PPO],
    normalizer: Optional[VecNormalize],
    deterministic: bool = True,
    rollout_seed: int = VALIDATION_SEED,
) -> Dict[str, Any]:
    """
    model=None: nominal predefined path, actions [Delta v, Delta offset] = [0, 0].
    model=PPO : deterministic learned residual corrections.
    """
    # Fix both generators so the stochastic rollout is reproducible.
    np.random.seed(rollout_seed)
    torch.manual_seed(rollout_seed)
    env = ColdSpray2DEnv(cfg, shared_target_bundle=bundle, env_seed=rollout_seed)
    obs, _ = env.reset(seed=rollout_seed)

    heights = [env.height.copy()]
    velocities: List[float] = []
    base_velocities: List[float] = []
    delta_vs: List[float] = []
    offsets: List[float] = []
    segments: List[Tuple[float, float, float, float]] = []

    while True:
        if model is None:
            action = np.zeros(2, dtype=np.float32)
        else:
            assert normalizer is not None
            normalized = normalizer.normalize_obs(batched(obs))
            predicted, _ = model.predict(normalized, deterministic=deterministic)
            action = np.asarray(predicted[0], dtype=np.float32)

        obs, _, terminated, truncated, info = env.step(action)
        heights.append(env.height.copy())
        velocities.append(float(info["velocity"]))
        base_velocities.append(float(info["local_base_velocity"]))
        delta_vs.append(float(info["dv"]))
        offsets.append(float(info["offset"]))
        segments.append((info["x0"], info["y0"], info["x1"], info["y1"]))
        if terminated or truncated:
            break

    return {
        "target": env.target.copy(),
        "target_base": env.target_base.copy(),
        "target_modulation": env.target_modulation.copy(),
        "h0": env.h0_modification.copy(),
        "final": heights[-1],
        "heights": np.stack(heights),
        "velocity": np.asarray(velocities),
        "v_base": np.asarray(base_velocities),
        "delta_v": np.asarray(delta_vs),
        "offset": np.asarray(offsets),
        "segments": np.asarray(segments),
        "rel_mse": relative_mse(heights[-1], env.target),
    }


def draw_path_comparison(
    ax,
    nominal_segments: np.ndarray,
    executed_segments: np.ndarray,
    title: str,
    visual_scale: float = PATH_VISUAL_SCALE,
):
    """Show nominal, true executed, and visually magnified path displacement."""
    from matplotlib.collections import LineCollection

    nominal = nominal_segments.reshape(-1, 2, 2)
    executed = executed_segments.reshape(-1, 2, 2)
    magnified = nominal + visual_scale * (executed - nominal)

    ax.add_collection(LineCollection(
        nominal, colors="0.25", linewidths=2.2, linestyles="dashed",
        label="predefined snake",
    ))
    ax.add_collection(LineCollection(
        executed, colors="tab:red", linewidths=2.8,
        label="executed (true scale)",
    ))
    ax.add_collection(LineCollection(
        magnified, colors="tab:blue", linewidths=2.1, alpha=0.9,
        label=fr"executed deviation $\times${visual_scale:g}",
    ))
    ax.set_xlim(0.0, 1.0)
    ax.set_ylim(0.0, 1.0)
    ax.set_aspect("equal")
    ax.set_xlabel("x")
    ax.set_ylabel("y")
    ax.set_title(title, fontweight="bold")


def _show_height(ax, data, title, vmin, vmax, cmap="viridis"):
    im = ax.imshow(
        data, origin="lower", extent=[0, 1, 0, 1],
        cmap=cmap, vmin=vmin, vmax=vmax,
    )
    ax.set_title(title, fontweight="bold")
    ax.set_xlabel("x")
    ax.set_ylabel("y")
    plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)


def _show_h0_difference(ax, difference, title, abs_limit):
    """
    Show h0_after_GP - nominal_h0 with a zero-centred colour scale.

    A diverging map makes positive and negative GP perturbations visible even
    when their amplitude is tiny compared with the absolute target height.
    """
    im = ax.imshow(
        difference,
        origin="lower",
        extent=[0, 1, 0, 1],
        cmap="RdBu_r",
        vmin=-abs_limit,
        vmax=abs_limit,
    )
    ax.set_title(title, fontweight="bold")
    ax.set_xlabel("x")
    ax.set_ylabel("y")
    cbar = plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    #cbar.set_label(r"$h_{\mathrm{target,GP}}-h_{\mathrm{target,nominal}}$")
    cbar.formatter.set_powerlimits((-2, 2))
    cbar.update_ticks()


def plot_controls(results: Dict[float, Dict[str, Any]]) -> Path:
    """
    Figure 1: two columns only.

    Deterministic and stochastic controls are overlaid in the same velocity
    panel and the same offset panel so the comparison stays thesis-readable.
    """
    # A larger canvas and one shared legend keep every panel readable after
    # the figure is scaled down to thesis page width.
    fig, axes = plt.subplots(3, 2, figsize=(21, 17))

    for row, amp in enumerate(AMPLITUDES):
        item = results[amp]
        det = item["deterministic"]
        sto = item["stochastic"]
        t = np.arange(len(det["velocity"]))

        ax = axes[row, 0]
        ax.plot(
            t, det["v_base"], "--", color="0.20", lw=3.4,
            label=r"predefined $v_{\mathrm{base}}$",
        )
        ax.plot(
            t, det["velocity"], color="tab:blue", lw=3.1,
            label="deterministic",
        )
        ax.plot(
            t, sto["velocity"], color="tab:orange", lw=2.8, alpha=0.90,
            label="stochastic",
        )
        ax.set_title(f"{100*amp:.0f}% GP — velocity", fontweight="bold")
        ax.set_ylabel("velocity")
        # A shared x meaning is obvious across rows; write the label only on
        # the bottom row so it cannot collide with the shared legend.
        if row == len(AMPLITUDES) - 1:
            ax.set_xlabel("deposition step", labelpad=10)
        ax.grid(alpha=0.25)

        ax = axes[row, 1]
        ax.axhline(
            0.0, color="0.20", lw=3.2, ls="--",
            label="predefined offset = 0",
        )
        ax.plot(
            t, det["offset"], color="tab:blue", lw=3.1,
            label="deterministic",
        )
        ax.plot(
            t, sto["offset"], color="tab:orange", lw=2.8, alpha=0.90,
            label="stochastic",
        )
        ax.set_title(f"{100*amp:.0f}% GP — offset", fontweight="bold")
        ax.set_ylabel(r"$\Delta$offset")
        if row == len(AMPLITUDES) - 1:
            ax.set_xlabel("deposition step", labelpad=10)
        ax.grid(alpha=0.25)

    # Write the line key once for the whole diagram.  Custom handles combine
    # the two different predefined labels into one concise reference entry.
    shared_handles = [
        plt.Line2D(
            [0], [0], color="0.20", lw=3.4, ls="--",
            label=r"predefined control ($v_{\mathrm{base}}$, offset = 0)",
        ),
        plt.Line2D(
            [0], [0], color="tab:blue", lw=3.1,
            label="deterministic PPO",
        ),
        plt.Line2D(
            [0], [0], color="tab:orange", lw=2.8,
            label="stochastic PPO",
        ),
    ]
    fig.legend(
        handles=shared_handles,
        loc="lower center",
        bbox_to_anchor=(0.5, 0.012),
        ncol=3,
        frameon=False,
        handlelength=3.0,
        columnspacing=2.4,
    )

    fig.suptitle(
        "Deterministic and stochastic PPO controls",
        fontsize=30, fontweight="bold",
    )
    # Reserve explicit bands for the suptitle and the single shared legend.
    # Figure-level legends are not accounted for reliably by
    # constrained_layout, which previously caused the legend to overlap the
    # bottom-row x labels.
    fig.subplots_adjust(
        left=0.075,
        right=0.985,
        top=0.925,
        bottom=0.145,
        hspace=0.34,
        wspace=0.20,
    )
    out = OUTPUT_DIR / "figure_1_velocity_offset.png"
    fig.savefig(out, dpi=220, bbox_inches="tight", pad_inches=0.12)
    plt.close(fig)
    return out


def plot_targets_and_paths(results: Dict[float, Dict[str, Any]]) -> Path:
    """
    Figure 2: exactly three columns.

    A single nominal target | GP-induced h0 difference by amplitude |
    deterministic executed path by amplitude.
    """
    fig = plt.figure(figsize=(19, 14), constrained_layout=True)
    grid = fig.add_gridspec(3, 3, width_ratios=(1.08, 1.0, 1.0))
    nominal_ax = fig.add_subplot(grid[:, 0])
    difference_axes = [fig.add_subplot(grid[row, 1]) for row in range(3)]
    path_axes = [fig.add_subplot(grid[row, 2]) for row in range(3)]

    nominal_target = results[AMPLITUDES[0]]["target"]
    vmin = float(np.min(nominal_target))
    vmax = float(np.max(nominal_target))

    differences = {
        # nominal h0 is the zero surface, so this is h0_GP - h0_nominal.
        amp: results[amp]["h0"]
        for amp in AMPLITUDES
    }
    difference_abs_limit = max(
        float(np.max(np.abs(difference)))
        for difference in differences.values()
    )
    # Avoid a singular colour normalization if every requested GP amplitude is 0.
    difference_abs_limit = max(difference_abs_limit, np.finfo(float).eps)

    # The nominal target is identical for all GP amplitudes, so show it once.
    _show_height(
        nominal_ax,
        nominal_target,
        "Nominal target",
        vmin,
        vmax,
    )

    for row, amp in enumerate(AMPLITUDES):
        item = results[amp]
        percentage_title = f"{100*amp:.0f}%"
        _show_h0_difference(
            difference_axes[row],
            differences[amp],
            percentage_title,
            difference_abs_limit,
        )
        draw_path_comparison(
            path_axes[row],
            item["baseline"]["segments"],
            item["deterministic"]["segments"],
            percentage_title,
        )

    # Column labels belong below the last diagrams; the diagram titles above
    # remain the perturbation levels only (0%, 5%, and 10%).
    difference_axes[-1].set_xlabel(
        r"$h_0$ difference", fontweight="bold", labelpad=12
    )
    path_axes[-1].set_xlabel(
        "Deterministic path", fontweight="bold", labelpad=12
    )

    # One shared legend, outside all axes, so it never covers the snake path.
    legend_handles, legend_labels = path_axes[0].get_legend_handles_labels()
    fig.legend(
        legend_handles,
        legend_labels,
        loc="upper center",
        bbox_to_anchor=(0.5, -0.01),
        ncol=3,
        frameon=False,
        handlelength=3.2,
        columnspacing=2.2,
    )

    fig.suptitle(
        r"Nominal target, GP-induced $h_0$ difference, and deterministic executed path",
        fontsize=24, fontweight="bold",
    )
    out = OUTPUT_DIR / "figure_2_h0_difference_path.png"
    fig.savefig(out, dpi=220, bbox_inches="tight")
    plt.close(fig)
    return out



def save_metrics(results: Dict[float, Dict[str, Any]]) -> Path:
    out = OUTPUT_DIR / "h0_gp_validation_metrics.csv"
    rows = [
        "h0_gp_amplitude,predefined_rel_mse,deterministic_rel_mse,"
        "stochastic_rel_mse,deterministic_improvement_percent,"
        "stochastic_improvement_percent"
    ]
    for amp in AMPLITUDES:
        b = results[amp]["baseline"]["rel_mse"]
        d = results[amp]["deterministic"]["rel_mse"]
        s = results[amp]["stochastic"]["rel_mse"]
        d_imp = 100.0 * (b - d) / max(b, 1e-12)
        s_imp = 100.0 * (b - s) / max(b, 1e-12)
        rows.append(
            f"{amp:.2f},{b:.10e},{d:.10e},{s:.10e},{d_imp:.6f},{s_imp:.6f}"
        )
    out.write_text("\n".join(rows) + "\n", encoding="utf-8")
    return out


def main() -> None:
    required_paths = set(MODEL_PATHS.values()) | set(VECNORMALIZE_PATHS.values())
    missing = [path for path in sorted(required_paths, key=str) if not path.exists()]
    if missing:
        formatted = "\n".join(f"  - {path}" for path in missing)
        raise FileNotFoundError(
            "Upload all required model/VecNormalize checkpoints:\n" + formatted
        )

    template = ColdSpray2DConfig()
    results: Dict[float, Dict[str, Any]] = {}
    loaded_models: Dict[Path, PPO] = {}

    for amp in AMPLITUDES:
        model_path = MODEL_PATHS[amp]
        vecnormalize_path = VECNORMALIZE_PATHS[amp]
        if model_path not in loaded_models:
            loaded_models[model_path] = load_checkpoint_compatible_model(model_path)
        model = loaded_models[model_path]

        print(f"\nRunning h0-GP amplitude {100*amp:.0f}% ...")
        print(f"  model: {model_path.name}")
        print(f"  VecNormalize: {vecnormalize_path.name}")
        cfg, bundle = make_fixed_h0_bundle(amp, template, VALIDATION_SEED)
        normalizer = make_normalizer(cfg, bundle, vecnormalize_path)
        validate_normalizer_compatibility(model, normalizer)

        baseline = run_rollout(
            cfg, bundle, model=None, normalizer=None,
            deterministic=True, rollout_seed=VALIDATION_SEED,
        )
        deterministic = run_rollout(
            cfg, bundle, model=model, normalizer=normalizer,
            deterministic=True, rollout_seed=VALIDATION_SEED,
        )
        stochastic = run_rollout(
            cfg, bundle, model=model, normalizer=normalizer,
            deterministic=False, rollout_seed=VALIDATION_SEED + 1000 + int(100 * amp),
        )
        results[amp] = {
            "target": bundle.target.copy(),
            "target_base": bundle.target_base.copy(),
            "h0": bundle.h0_modification.copy(),
            "baseline": baseline,
            "deterministic": deterministic,
            "stochastic": stochastic,
        }
        print(
            f"  predefined relMSE = {baseline['rel_mse']:.6e} | "
            f"deterministic PPO = {deterministic['rel_mse']:.6e} | "
            f"stochastic PPO = {stochastic['rel_mse']:.6e}"
        )
        normalizer.close()

    outputs = [plot_combined_validation(results), save_metrics(results)]
    print("\nSaved outputs:")
    for path in outputs:
        print(f"  {path}")


if __name__ == "__main__":
    main()
def format_profile_box_text(
    amp_percent: float,
    rel_mse: float,
    overshoot: float,
) -> str:
    return "\n".join(
        [
            f"h0 = {amp_percent:.2f}%",
            f"relMSE = {rel_mse:.3e}",
            f"overshoot = {overshoot:.3e}",
        ]
    )


def add_annotation_box(ax, text: str, fontsize: float = 7.0, loc: str = "upper left") -> None:
    if loc == "upper left":
        x, y, ha, va = 0.02, 0.98, "left", "top"
    elif loc == "upper right":
        x, y, ha, va = 0.98, 0.98, "right", "top"
    else:
        x, y, ha, va = 0.02, 0.98, "left", "top"

    ax.text(
        x,
        y,
        text,
        transform=ax.transAxes,
        ha=ha,
        va=va,
        fontsize=fontsize,
        bbox=dict(
            boxstyle="round",
            facecolor="white",
            alpha=0.88,
            edgecolor="0.4",
        ),
    )


def set_column_headers(axes, n_cases: int) -> None:
    headers = [
        "Deterministic",
        "Stochastic",
        "Stochastic reward",
        r"Stochastic velocity / $\delta v$",
    ]
    for j, header in enumerate(headers):
        if n_cases == 1:
            axes[j].set_title(header, fontsize=12.5, fontweight="bold")
        else:
            axes[0, j].set_title(header, fontsize=12.5, fontweight="bold")


def plot_height_panel(
    ax,
    data: Dict[str, Any],
    amp_percent: float,
    add_row_label: Optional[str] = None,
    show_legend: bool = True,
) -> None:
    x = data["x_grid"]
    target = data["target"]
    target_base = data["target_base"]
    h0 = data["h0"]
    final_height = data["final_height"]

    rel_mse = float(data["relative_mse"])
    overshoot = float(data["max_overshoot"])

    ax.plot(x, final_height, linewidth=2.0, label="height")
    ax.plot(x, target, linewidth=1.8, alpha=0.80, label="target")
    ax.plot(x, target_base, linewidth=1.8, alpha=0.80, label="target_base")
    ax.plot(x, h0, linewidth=1.5, alpha=0.80, label="h0_modification")

    y_all = np.concatenate([final_height, target, target_base, h0])
    y_min = float(np.min(y_all))
    y_max = float(np.max(y_all))
    margin = 0.10 * max(y_max - y_min, 1e-6)
    ax.set_ylim(y_min - margin, y_max + margin)

    ax.set_xlabel("x")
    ax.set_ylabel("height")

    if show_legend:
        ax.legend(loc="lower right", fontsize=6.4)

    box_text = format_profile_box_text(
        amp_percent=amp_percent,
        rel_mse=rel_mse,
        overshoot=overshoot,
    )
    add_annotation_box(ax, box_text, fontsize=6.8, loc="upper left")

    if add_row_label is not None:
        ax.text(
            -0.18,
            0.5,
            add_row_label,
            transform=ax.transAxes,
            rotation=90,
            ha="center",
            va="center",
            fontsize=8.8,
            fontweight="bold",
        )


def plot_reward_panel(
    ax,
    stoch: Dict[str, Any],
    amp_percent: float,
) -> None:
    rewards = stoch["rewards"]
    if len(rewards) > 0:
        t = np.arange(len(rewards), dtype=np.float32)
        ax.plot(t, rewards, linewidth=1.8)

    ax.set_xlabel("step")
    ax.set_ylabel("reward")

    box_text = format_profile_box_text(
        amp_percent=amp_percent,
        rel_mse=float(stoch["relative_mse"]),
        overshoot=float(stoch["max_overshoot"]),
    )
    add_annotation_box(ax, box_text, fontsize=6.8, loc="upper left")


def plot_velocity_panel(
    ax,
    stoch: Dict[str, Any],
    amp_percent: float,
) -> None:
    """Show the executed stochastic velocity and the learned residual correction delta_v.

    The environment applies

        v = clip(v_base(x) + delta_v, v_min, v_max),

    where delta_v is the residual action produced by the RL policy after scaling.
    Showing v_base, v, and delta_v makes the learned correction visible.
    """
    vs = stoch["vs"]
    local_base_vs = stoch.get("local_base_vs", np.array([], dtype=np.float32))
    dvs = stoch.get("dvs", np.array([], dtype=np.float32))

    if len(dvs) > 0:
        t = np.arange(len(dvs), dtype=np.float32)

        # v and v_base are segment quantities. Use vs[1:] and local_base_vs[1:]
        # to align them with delta_v at each rollout step.
        v_exec = vs[1: 1 + len(dvs)]
        v_base = local_base_vs[1: 1 + len(dvs)] if len(local_base_vs) > 1 else v_exec - dvs

        ax.plot(t, v_exec, linewidth=1.8, label="v")
        ax.plot(t, v_base, linewidth=1.3, linestyle="--", label=r"$v_{base}$")
        ax.set_xlabel("step")
        ax.set_ylabel("v")
        ax.legend(loc="lower left", fontsize=6.2)

        ax_delta = ax.twinx()
        ax_delta.plot(t, dvs, linewidth=1.5, linestyle=":", label=r"$\delta v$")
        ax_delta.axhline(0.0, linewidth=0.8, linestyle="--", alpha=0.6)
        ax_delta.set_ylabel(r"$\delta v$")
        ax_delta.legend(loc="lower right", fontsize=7.0)
    else:
        # Fallback for older result dictionaries.
        if len(vs) > 0:
            tv = np.arange(len(vs), dtype=np.float32)
            ax.plot(tv, vs, linewidth=1.8, label="v")
            ax.legend(loc="lower left", fontsize=7.0)
        ax.set_xlabel("step")
        ax.set_ylabel("v")

    mean_abs_dv = float(np.mean(np.abs(dvs))) if len(dvs) > 0 else 0.0
    max_abs_dv = float(np.max(np.abs(dvs))) if len(dvs) > 0 else 0.0

    box_text = "\n".join(
        [
            fr"mean|$\delta v$| = {mean_abs_dv:.3e}",
            fr"max|$\delta v$| = {max_abs_dv:.3e}",
        ]
    )
    add_annotation_box(ax, box_text, fontsize=6.2, loc="upper left")


def plot_combined_reference_style(results: List[Dict[str, Any]], out_dir: Path):
    n_cases = len(results)

    fig, axes = plt.subplots(
        n_cases,
        4,
        figsize=(20.0, 3.10 * n_cases),
        sharex=False,
    )

    if n_cases == 1:
        axes = axes[None, :]

    set_column_headers(axes, n_cases)

    for row, item in enumerate(results):
        det = item["det"]
        stoch = item["stoch"]

        amp_percent = 100.0 * item["h0_relative_amplitude"]
        checkpoint_label = item["checkpoint_label"]
        global_case = item["global_case_index"]

        row_label = f"Val {global_case}"

        plot_height_panel(
            axes[row, 0],
            det,
                amp_percent=amp_percent,
            add_row_label=row_label,
            show_legend=True,
        )
        plot_height_panel(
            axes[row, 1],
            stoch,
                amp_percent=amp_percent,
            add_row_label=None,
            show_legend=True,
        )
        plot_reward_panel(
            axes[row, 2],
            stoch,
                amp_percent=amp_percent,
        )
        plot_velocity_panel(
            axes[row, 3],
            stoch,
                amp_percent=amp_percent,
        )

    plt.tight_layout()

    png_path = out_dir / "thesis_combined_10_tests_reference_style_v4.png"
    pdf_path = out_dir / "thesis_combined_10_tests_reference_style_v4.pdf"

    fig.savefig(png_path, dpi=FIG_DPI, bbox_inches="tight")
    fig.savefig(pdf_path, bbox_inches="tight")

    plt.show()

    print(f"Saved PNG to: {png_path}")
    print(f"Saved PDF to: {pdf_path}")

    return png_path, pdf_path



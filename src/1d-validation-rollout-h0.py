def check_checkpoint_files(test_groups: List[Dict[str, Any]]) -> None:
    if not CHECKPOINT_DIR.exists():
        raise FileNotFoundError(
            f"CHECKPOINT_DIR does not exist: {CHECKPOINT_DIR}\n"
            "Please mount Google Drive and/or fix CHECKPOINT_DIR."
        )

    required = []
    for group in test_groups:
        prefix = group["model_prefix"]
        required.append(CHECKPOINT_DIR / f"{prefix}.zip")
        required.append(CHECKPOINT_DIR / f"{prefix}_vecnormalize.pkl")

    missing = [p for p in required if not p.exists()]
    if missing:
        available = sorted([p.name for p in CHECKPOINT_DIR.glob("*")])
        raise FileNotFoundError(
            "Missing required checkpoint files:\n"
            + "\n".join(str(p) for p in missing)
            + "\n\nAvailable files in CHECKPOINT_DIR:\n"
            + "\n".join(available[:100])
        )


def load_model_bundle(model_prefix: str) -> Tuple[PPO, VecNormalize]:
    model_path = CHECKPOINT_DIR / f"{model_prefix}.zip"
    vecnorm_path = CHECKPOINT_DIR / f"{model_prefix}_vecnormalize.pkl"

    base_venv = make_base_vec_env_for_loading()

    venv = VecNormalize.load(str(vecnorm_path), base_venv)
    venv.training = False
    venv.norm_reward = False

    device = "cuda" if torch.cuda.is_available() else "cpu"

    model = PPO.load(
        str(model_path),
        env=venv,
        device=device,
    )

    # Shape diagnostic. This catches the most common mismatch early.
    expected_obs_dim = 2 * cfg.n_bins + 4
    actual_obs_shape = venv.observation_space.shape
    if actual_obs_shape != (expected_obs_dim,):
        raise ValueError(
            f"Observation shape mismatch for {model_prefix}: "
            f"venv.observation_space.shape = {actual_obs_shape}, "
            f"expected = {(expected_obs_dim,)}. "
            "This usually means cfg.n_bins or the environment definition does not match training."
        )

    print("=" * 80)
    print(f"Loaded model:        {model_path}")
    print(f"Loaded VecNormalize: {vecnorm_path}")
    print(f"Device:              {device}")
    print(f"Observation shape:   {actual_obs_shape}")
    print("=" * 80)

    return model, venv



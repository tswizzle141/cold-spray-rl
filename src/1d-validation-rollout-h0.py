@dataclass
class GPProfiles:
    x_grid: np.ndarray
    v_base_vec: np.ndarray
    target_base: np.ndarray
    target: np.ndarray
    h0_modification: np.ndarray
    baseline_deposition: np.ndarray
    g_base: np.ndarray
    g_h0: np.ndarray
    sampled_h0_mod_relative_amplitude: float


def build_fixed_h0_gp_profiles(
    cfg: ColdSpray1DConfig,
    rng: np.random.Generator,
    h0_relative_amplitude: float,
) -> GPProfiles:
    x_grid = np.linspace(0.0, cfg.x_max, cfg.n_bins, dtype=np.float32)
    dx = float(x_grid[1] - x_grid[0])

    # GP for nominal base velocity
    g_base = sample_zero_mean_gp(
        rng=rng,
        x_grid=x_grid,
        std=cfg.gp_std,
        lengthscale=cfg.gp_lengthscale,
        jitter=cfg.gp_jitter,
    )

    v_base_raw = float(cfg.base_v) + float(cfg.v_base_gp_amplitude) * g_base.astype(np.float64)
    v_base_vec = np.clip(v_base_raw, cfg.v_min, cfg.v_max).astype(np.float32)

    # Nominal Gaussian slicer target from flat h0
    baseline_deposition = (
        cfg.feed_rate * dx / np.maximum(v_base_vec, 1e-12)
    ).astype(np.float32)

    target_base = baseline_deposition.copy()
    target = np.maximum(target_base, 0.0).astype(np.float32)

    # GP for initial surface h0
    g_h0 = sample_zero_mean_gp(
        rng=rng,
        x_grid=x_grid,
        std=cfg.gp_std,
        lengthscale=cfg.gp_lengthscale,
        jitter=cfg.gp_jitter,
    )

    h0_modification = (
        float(h0_relative_amplitude)
        * float(np.mean(baseline_deposition.astype(np.float64)))
        * g_h0.astype(np.float64)
    ).astype(np.float32)

    h0_modification = (h0_modification - np.mean(h0_modification)).astype(np.float32)

    return GPProfiles(
        x_grid=x_grid.copy(),
        v_base_vec=v_base_vec.copy(),
        target_base=target_base.copy(),
        target=target.copy(),
        h0_modification=h0_modification.copy(),
        baseline_deposition=baseline_deposition.copy(),
        g_base=g_base.copy(),
        g_h0=g_h0.copy(),
        sampled_h0_mod_relative_amplitude=float(h0_relative_amplitude),
    )



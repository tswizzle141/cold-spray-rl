def rollout_one_case(
    model: PPO,
    venv: VecNormalize,
    cfg: ColdSpray1DConfig,
    h0_relative_amplitude: float,
    env_seed: int,
    deterministic: bool = True,
    stochastic_seed_offset: int = 100000,
) -> Dict[str, Any]:
    if deterministic:
        torch.manual_seed(GLOBAL_TORCH_SEED + int(env_seed))
        np.random.seed(GLOBAL_TORCH_SEED + int(env_seed))
    else:
        torch.manual_seed(GLOBAL_TORCH_SEED + int(env_seed) + stochastic_seed_offset)
        np.random.seed(GLOBAL_TORCH_SEED + int(env_seed) + stochastic_seed_offset)

    env = ColdSpray1DTestEnv(
        cfg=cfg,
        h0_relative_amplitude=h0_relative_amplitude,
        env_seed=env_seed,
    )

    obs, _ = env.reset()

    n = cfg.n_bins

    heights: List[np.ndarray] = [obs[:n].copy()]
    xs: List[float] = [0.0]
    vs: List[float] = [float(obs[2 * n + 2])]
    local_base_vs: List[float] = [float(obs[2 * n + 3])]
    dvs: List[float] = []
    rewards: List[float] = []
    actions: List[float] = []
    mses: List[float] = []
    overshoots: List[float] = []

    for _ in range(cfg.n_steps):
        obs_norm = venv.normalize_obs(obs[None, :].astype(np.float32))
        action, _ = model.predict(obs_norm, deterministic=deterministic)

        action_env = action[0]
        obs, reward, terminated, truncated, info = env.step(action_env)

        heights.append(obs[:n].copy())
        xs.append(float(info["nozzle_x"]))
        vs.append(float(info["velocity"]))
        local_base_vs.append(float(info["local_base_velocity"]))
        dvs.append(float(info["dv"]))
        rewards.append(float(reward))
        actions.append(float(np.asarray(action_env).reshape(-1)[0]))
        mses.append(float(info["mse"]))
        overshoots.append(float(info["max_overshoot"]))

        if terminated or truncated:
            break

    heights = np.stack(heights, axis=0)

    final_height = heights[-1].copy()
    target = env.target.copy()
    h0 = env.h0_modification.copy()

    relative_mse = compute_relative_mse_mean_target(final_height, target)
    mae = compute_mean_abs_error(final_height, target)
    max_overshoot = compute_max_overshoot(final_height, target)

    return {
        "x_grid": env.x_grid.copy(),
        "target": target,
        "target_base": env.target_base.copy(),
        "h0": h0,
        "final_height": final_height,
        "heights": heights,
        "v_base_vec": env.v_base_vec.copy(),
        "vs": np.array(vs, dtype=np.float32),
        "local_base_vs": np.array(local_base_vs, dtype=np.float32),
        "dvs": np.array(dvs, dtype=np.float32),
        "xs": np.array(xs, dtype=np.float32),
        "actions": np.array(actions, dtype=np.float32),
        "rewards": np.array(rewards, dtype=np.float32),
        "mses": np.array(mses, dtype=np.float32),
        "overshoots": np.array(overshoots, dtype=np.float32),
        "h0_relative_amplitude": float(h0_relative_amplitude),
        "seed": int(env_seed),
        "relative_mse": float(relative_mse),
        "mae": float(mae),
        "max_overshoot": float(max_overshoot),
        "h0_std": float(np.std(h0)),
        "target_mean": float(np.mean(target)),
    }



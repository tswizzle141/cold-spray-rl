class ColdSpray2DMultiInputExtractor(BaseFeaturesExtractor):
    def __init__(
        self,
        observation_space: spaces.Dict,
        cnn_output_dim: int = 128,
        state_output_dim: int = 32,
    ) -> None:
        super().__init__(
            observation_space,
            features_dim=cnn_output_dim + state_output_dim,
        )
        map_space = observation_space["map"]
        state_space = observation_space["state"]
        n_map_channels = int(map_space.shape[0])
        n_state = int(state_space.shape[0])

        self.map_cnn = nn.Sequential(
            nn.Conv2d(n_map_channels, 16, kernel_size=3, stride=1, padding=1),
            nn.ReLU(),
            nn.Conv2d(16, 32, kernel_size=3, stride=1, padding=1),
            nn.ReLU(),
            nn.Conv2d(32, 32, kernel_size=3, stride=1, padding=1),
            nn.ReLU(),
            nn.AdaptiveAvgPool2d((1, 1)),
            nn.Flatten(),
        )
        with torch.no_grad():
            sample_map = torch.as_tensor(map_space.sample()[None]).float()
            n_flatten = int(self.map_cnn(sample_map).shape[1])

        self.map_head = nn.Sequential(
            nn.Linear(n_flatten, cnn_output_dim),
            nn.ReLU(),
        )
        self.state_mlp = nn.Sequential(
            nn.Linear(n_state, 64),
            nn.ReLU(),
            nn.Linear(64, state_output_dim),
            nn.ReLU(),
        )

    def forward(self, observations: Dict[str, torch.Tensor]) -> torch.Tensor:
        map_features = self.map_head(self.map_cnn(observations["map"].float()))
        state_features = self.state_mlp(observations["state"].float())
        return torch.cat([map_features, state_features], dim=1)


class DummyDictEnv(gym.Env):
    """Only supplies the spaces needed to restore VecNormalize."""

    def __init__(self, cfg: Config):
        super().__init__()
        self.observation_space = spaces.Dict(
            {
                "map": spaces.Box(
                    -np.inf,
                    np.inf,
                    shape=(2, cfg.grid_n, cfg.grid_n),
                    dtype=np.float32,
                ),
                "state": spaces.Box(
                    -np.inf,
                    np.inf,
                    shape=(5,),
                    dtype=np.float32,
                ),
            }
        )
        self.action_space = spaces.Box(-1.0, 1.0, shape=(2,), dtype=np.float32)

    def reset(self, *, seed=None, options=None):
        super().reset(seed=seed)
        return {
            "map": np.zeros((2, CFG.grid_n, CFG.grid_n), np.float32),
            "state": np.zeros(5, np.float32),
        }, {}

    def step(self, action):
        obs, _ = self.reset()
        return obs, 0.0, False, True, {}


def load_agent(cfg: Config) -> Tuple[PPO, VecNormalize]:
    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            f"Model not found: {MODEL_PATH}\n"
            "Edit MODEL_PATH at the top of this script."
        )
    if not VECNORMALIZE_PATH.exists():
        raise FileNotFoundError(
            f"VecNormalize not found: {VECNORMALIZE_PATH}\n"
            "best_model_13 must be used with its matching VecNormalize file."
        )

    dummy = DummyVecEnv([lambda: DummyDictEnv(cfg)])
    vecnorm = VecNormalize.load(str(VECNORMALIZE_PATH), dummy)
    vecnorm.training = False
    vecnorm.norm_reward = False

    device = "cuda" if torch.cuda.is_available() else "cpu"

    # IMPORTANT:
    # Some best_model_13 checkpoints do not restore the serialized custom
    # extractor entry in policy_kwargs.  In that case SB3 silently constructs
    # its default CombinedExtractor, which flattens this observation to
    # 2*32*32 + 5 = 2053 features.  The saved actor/critic weights, however,
    # were trained with ColdSpray2DMultiInputExtractor and therefore expect
    # 128 + 32 = 160 features.  Supplying policy_kwargs via custom_objects
    # forces SB3 to reconstruct the exact training architecture before loading
    # the state_dict.
    exact_policy_kwargs = {
        "log_std_init": -4.0,
        "features_extractor_class": ColdSpray2DMultiInputExtractor,
        "features_extractor_kwargs": {
            "cnn_output_dim": 128,
            "state_output_dim": 32,
        },
    }
    model = PPO.load(
        str(MODEL_PATH),
        env=vecnorm,
        device=device,
        custom_objects={"policy_kwargs": exact_policy_kwargs},
    )

    # Fail immediately with a useful message if a different checkpoint is
    # accidentally selected, rather than waiting for the first rollout.
    extractor = model.policy.features_extractor
    if not isinstance(extractor, ColdSpray2DMultiInputExtractor):
        raise RuntimeError(
            "Wrong policy architecture after loading: expected "
            "ColdSpray2DMultiInputExtractor, got "
            f"{type(extractor).__name__}."
        )
    if int(extractor.features_dim) != 160:
        raise RuntimeError(
            "Wrong extractor output size: expected 160 "
            f"(128 CNN + 32 state), got {extractor.features_dim}."
        )
    if model.observation_space != dummy.observation_space:
        raise RuntimeError(
            "Checkpoint observation space does not match best_model_13: "
            f"checkpoint={model.observation_space}, expected={dummy.observation_space}."
        )

    print(f"[OK] Loaded model: {MODEL_PATH}")
    print(f"[OK] Loaded VecNormalize: {VECNORMALIZE_PATH}")
    print("[OK] Policy architecture: custom CNN+MLP extractor (160 features)")
    print(f"[OK] Inference device: {device}")
    return model, vecnorm



def main() -> None:
    np.random.seed(RANDOM_SEED)
    torch.manual_seed(RANDOM_SEED)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    print("2D layer-by-layer print with best_model_13")
    print(f"layers={N_LAYERS}, max thickness/layer={LAYER_THICKNESS}")
    print(f"outputs={OUTPUT_DIR}")

    model, vecnorm = load_agent(CFG)
    steps = SnakePath2D(CFG).steps()
    deposition = DepositionModel2D(CFG)
    slicer = AdaptiveSlicer(CFG, steps, deposition)
    print(f"[OK] Snake path has {len(steps)} RL steps per layer")

    all_case_results = []
    for shape_name in SHAPES_TO_RUN:
        print("\n" + "#" * 80)
        print(f"RUNNING SHAPE: {shape_name}")
        cases = {
            "Slicer/original": run_case(
                shape_name, "Slicer/original", CFG, None, None,
                steps, deposition, slicer,
                use_rl=False, execution_modified=False,
            ),
            "Slicer/modified": run_case(
                shape_name, "Slicer/modified", CFG, None, None,
                steps, deposition, slicer,
                use_rl=False, execution_modified=True,
            ),
            "RL/modified": run_case(
                shape_name, "RL/modified", CFG, model, vecnorm,
                steps, deposition, slicer,
                use_rl=True, execution_modified=True,
            ),
        }
        save_all_outputs(cases)
        all_case_results.extend(cases.values())

    print_final_table(all_case_results)
    print(f"\n[DONE] All files saved under: {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
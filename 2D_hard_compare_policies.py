class SnakePath2D:
    def __init__(self, cfg: Config):
        self.cfg = cfg

    @staticmethod
    def _cumlen(points: np.ndarray) -> np.ndarray:
        d = points[1:] - points[:-1]
        return np.r_[0.0, np.cumsum(np.linalg.norm(d, axis=1))]

    def polyline(self) -> Tuple[np.ndarray, np.ndarray]:
        n = self.cfg.grid_n
        points: List[List[float]] = []
        direction = 1
        py = 0
        while py <= n - 1:
            px0, px1 = (0, n - 1) if direction == 1 else (n - 1, 0)
            p0 = [(px0 + 0.5) / n, (py + 0.5) / n]
            p1 = [(px1 + 0.5) / n, (py + 0.5) / n]
            if not points or not np.allclose(points[-1], p0):
                points.append(p0)
            points.append(p1)
            py_next = py + self.cfg.spacing_px
            if py_next <= n - 1:
                points.append([(px1 + 0.5) / n, (py_next + 0.5) / n])
            direction *= -1
            py = py_next
        pts = np.asarray(points, dtype=np.float64)
        return pts, self._cumlen(pts)

    @staticmethod
    def pose_at_s(
        pts: np.ndarray,
        cumlen: np.ndarray,
        s: float,
    ) -> Tuple[float, float, float, float]:
        s = float(np.clip(s, 0.0, cumlen[-1]))
        i = int(np.clip(np.searchsorted(cumlen, s, side="right") - 1, 0, len(cumlen) - 2))
        denom = max(float(cumlen[i + 1] - cumlen[i]), 1e-12)
        a = (s - float(cumlen[i])) / denom
        p = (1.0 - a) * pts[i] + a * pts[i + 1]
        d = pts[i + 1] - pts[i]
        d /= max(float(np.linalg.norm(d)), 1e-12)
        return float(p[0]), float(p[1]), float(d[0]), float(d[1])

    def steps(self) -> List[dict]:
        pts, cumlen = self.polyline()
        total = float(cumlen[-1])
        s_values = np.arange(0.0, total, self.cfg.ds, dtype=np.float64)
        if len(s_values) == 0 or s_values[-1] < total:
            s_values = np.r_[s_values, total]

        out = []
        for s0, s1 in zip(s_values[:-1], s_values[1:]):
            x0, y0, tx0, ty0 = self.pose_at_s(pts, cumlen, float(s0))
            x1, y1, tx1, ty1 = self.pose_at_s(pts, cumlen, float(s1))
            tx, ty = 0.5 * (tx0 + tx1), 0.5 * (ty0 + ty1)
            norm = max(float(np.hypot(tx, ty)), 1e-12)
            tx, ty = tx / norm, ty / norm
            out.append(
                dict(
                    x0=x0, y0=y0, x1=x1, y1=y1,
                    tx=tx, ty=ty, nx=-ty, ny=tx,
                    length=max(float(s1 - s0), 1e-8),
                )
            )
        return out


def _smooth_2d_reflect(height: np.ndarray, window: int) -> np.ndarray:
    window = int(window)
    if window <= 1:
        return height.astype(np.float32, copy=True)
    if window % 2 == 0:
        window += 1
    pad = window // 2
    h = np.pad(height.astype(np.float64), ((pad, pad), (pad, pad)), mode="reflect")
    kernel = np.ones(window, dtype=np.float64) / window
    tmp = np.apply_along_axis(lambda row: np.convolve(row, kernel, mode="valid"), 1, h)
    out = np.apply_along_axis(lambda col: np.convolve(col, kernel, mode="valid"), 0, tmp)
    return out.astype(np.float32)


class DepositionModel2D:
    def __init__(self, cfg: Config):
        self.cfg = cfg
        n = cfg.grid_n
        self.pix_area = (1.0 / n) ** 2
        self.C = cfg.beta * self.pix_area / (
            2.0 * np.pi * cfg.sigma**2 * gamma(2.0 / cfg.beta)
        )
        grid = (np.arange(n, dtype=np.float64) + 0.5) / n
        self.Y, self.X = np.meshgrid(grid, grid, indexing="ij")

    def _kernel(self, r: np.ndarray) -> np.ndarray:
        c = self.cfg
        return c.A_amp * self.C * np.exp(-((r / c.sigma) ** c.beta))

    def basis_for_segment(
        self,
        x0: float,
        y0: float,
        x1: float,
        y1: float,
        height_for_geometry: Optional[np.ndarray] = None,
        modified: bool = False,
    ) -> np.ndarray:
        c = self.cfg
        dx, dy = x1 - x0, y1 - y0
        length = float(np.hypot(dx, dy))
        samples = max(
            1,
            int(np.ceil(length / ((1.0 / c.grid_n) / max(c.samples_per_pixel, 1e-6)))),
        )
        s = (np.arange(samples) + 0.5) / samples
        acc = np.zeros((c.grid_n, c.grid_n), dtype=np.float64)
        for a in s:
            x, y = x0 + a * dx, y0 + a * dy
            acc += self._kernel(np.hypot(self.X - x, self.Y - y))
        basis = (c.eta / (c.rho_m * self.pix_area)) * acc / samples

        if modified and height_for_geometry is not None:
            hs = _smooth_2d_reflect(height_for_geometry, c.slope_smoothing_window)
            dh_dy, dh_dx = np.gradient(hs.astype(np.float64), 1.0 / c.grid_n)
            grad = np.sqrt(dh_dx**2 + dh_dy**2)
            eta_geom = (1.0 + grad**2) ** (-0.5 * c.geometry_kernel_p)
            basis *= eta_geom
        return basis.astype(np.float32)


def clipped_shifted_segment(st: dict, offset: float) -> Tuple[float, float, float, float]:
    return tuple(
        float(np.clip(v, 0.0, 1.0))
        for v in (
            st["x0"] + offset * st["nx"],
            st["y0"] + offset * st["ny"],
            st["x1"] + offset * st["nx"],
            st["y1"] + offset * st["ny"],
        )
    )



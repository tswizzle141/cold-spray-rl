def make_final_target(shape_name: str, cfg: Config) -> np.ndarray:
    grid = (np.arange(cfg.grid_n, dtype=np.float64) + 0.5) / cfg.grid_n
    Y, X = np.meshgrid(grid, grid, indexing="ij")

    if shape_name == "full_rectangle":
        target = np.full_like(X, FINAL_MAX_HEIGHT)

    elif shape_name == "full_cylinder":
        radius = 0.5
        target = FINAL_MAX_HEIGHT * (
            (X - 0.5) ** 2 + (Y - 0.5) ** 2 <= radius**2
        )

    elif shape_name == "four_gaussian_bumps":
        # Use a dedicated seeded generator so this target is reproducible and
        # does not depend on any random numbers consumed elsewhere.  Rejection
        # sampling keeps the randomly positioned bumps visibly separated.
        rng = np.random.default_rng(RANDOM_SEED + 4004)
        centers: List[Tuple[float, float]] = []
        while len(centers) < 4:
            candidate = tuple(rng.uniform(0.16, 0.84, size=2))
            if all(
                np.hypot(candidate[0] - cx, candidate[1] - cy) >= 0.24
                for cx, cy in centers
            ):
                centers.append(candidate)

        # Different amplitudes and widths make the four bumps unequal in both
        # peak height and footprint while retaining the 0.10 m base slab.
        amplitudes = rng.uniform(0.050, 0.100, size=4)
        sigmas = rng.uniform(0.060, 0.095, size=4)
        target = np.full_like(X, 0.10)
        for (cx, cy), amplitude, sigma in zip(centers, amplitudes, sigmas):
            target += amplitude * np.exp(
                -((X - cx) ** 2 + (Y - cy) ** 2) / (2.0 * sigma**2)
            )
        target = np.minimum(target, FINAL_MAX_HEIGHT)
        print("[INFO] Random four-bump target (fixed seed):")
        for idx, ((cx, cy), amplitude, sigma) in enumerate(
            zip(centers, amplitudes, sigmas),
            start=1,
        ):
            print(
                f"       bump {idx}: center=({cx:.3f}, {cy:.3f}), "
                f"amplitude={amplitude:.3f}, sigma={sigma:.3f}"
            )

    elif shape_name == "edge_bump":
        target = 0.10 + 0.10 * np.exp(
            -((X - 0.08) ** 2 + (Y - 0.50) ** 2) / (2.0 * 0.08**2)
        )
        target = np.minimum(target, FINAL_MAX_HEIGHT)

    else:
        raise ValueError(f"Unknown shape: {shape_name}")

    return target.astype(np.float32)



def _finish_figure(fig: plt.Figure, path: Path) -> None:
    fig.savefig(path, dpi=250, bbox_inches="tight", facecolor="white")
    if SHOW_FIGURES_IN_COLAB:
        plt.show()
    plt.close(fig)


def _metric_text(metric: Dict[str, float]) -> str:
    """Format only the three metrics reported in the thesis figure."""
    return (
        rf"relMSE = {metric['relative_mse']:.3e}"
        rf"        maxOv = {metric['max_overshoot']:.3e}"
        rf"        rel. volume error = {metric['volume_error']:.2%}"
    )


def plot_final_target_and_selected_layers(
    result: Dict[str, Any],
    out_dir: Path,
) -> None:
    """One figure: final target preview plus selected cumulative 3D layers."""
    target = result["final_target"]
    selected = [0, 4, 9]
    n = target.shape[0]
    grid = (np.arange(n) + 0.5) / n
    X, Y = np.meshgrid(grid, grid)

    fig = plt.figure(figsize=(24, 17))
    gs = fig.add_gridspec(
        3,
        6,
        height_ratios=[1.08, 1.0, 1.0],
        hspace=0.38,
        wspace=0.42,
    )

    ax_map = fig.add_subplot(gs[0, 0:3])
    ax_surface = fig.add_subplot(gs[0, 3:6], projection="3d")
    im = ax_map.imshow(
        target,
        origin="lower",
        extent=[0, 1, 0, 1],
        cmap="viridis",
    )
    ax_map.set(title="Final target height map", xlabel="x", ylabel="y")
    fig.colorbar(im, ax=ax_map, label="height")
    ax_surface.plot_surface(X, Y, target, cmap="viridis", linewidth=0)
    ax_surface.set(
        title="Final target surface",
        xlabel="x",
        ylabel="y",
        zlabel="height",
    )
    ax_surface.set_zlim(0, FINAL_MAX_HEIGHT * 1.20)

    for col, idx in enumerate(selected):
        panels = [
            (result["layer_targets"][idx], "Cumulative target"),
            (result["layer_heights"][idx], "Printed surface"),
        ]
        for row, (surface, title) in enumerate(panels, start=1):
            ax = fig.add_subplot(
                gs[row, 2 * col:2 * col + 2],
                projection="3d",
            )
            ax.plot_surface(X, Y, surface, cmap="viridis", linewidth=0)
            ax.set(
                title=f"Layer {idx + 1}/{N_LAYERS}: {title}",
                xlabel="x",
                ylabel="y",
                zlabel="height",
            )
            ax.set_zlim(0, FINAL_MAX_HEIGHT * 1.20)

    fig.suptitle(
        f"Final target and selected cumulative layers — {result['shape_name']}",
        fontsize=26,
        y=0.995,
    )
    _finish_figure(fig, out_dir / "01_final_target_and_selected_layers.png")


def plot_selected_policy_comparison(
    case_results: Dict[str, Dict[str, Any]],
    out_dir: Path,
) -> None:
    """
    Compare the three execution cases at layers 1, 5, and 10.

    Columns are execution cases and rows are selected cumulative layers.
    Every map has its own relMSE, maximum overshoot, and relative volume error
    directly underneath it.
    """
    selected = [0, 4, 9]
    case_order = ["Slicer/original", "Slicer/modified", "RL/modified"]
    missing = [name for name in case_order if name not in case_results]
    if missing:
        raise KeyError(f"Missing comparison cases: {missing}")

    shape_name = case_results[case_order[0]]["shape_name"]
    fig = plt.figure(figsize=(24, 23))
    gs = fig.add_gridspec(
        6,
        3,
        height_ratios=[1.0, 0.19, 1.0, 0.19, 1.0, 0.19],
        hspace=0.31,
        wspace=0.28,
    )

    for row, idx in enumerate(selected):
        map_row = 2 * row
        metric_row = map_row + 1
        layer_target = case_results[case_order[0]]["layer_targets"][idx]
        all_heights = [
            case_results[name]["layer_heights"][idx] for name in case_order
        ]
        common_min = float(min(np.min(layer_target), *(np.min(h) for h in all_heights)))
        common_max = float(max(np.max(layer_target), *(np.max(h) for h in all_heights)))

        for col, case_name in enumerate(case_order):
            result = case_results[case_name]
            ax = fig.add_subplot(gs[map_row, col])
            image = ax.imshow(
                result["layer_heights"][idx],
                origin="lower",
                extent=[0, 1, 0, 1],
                cmap="viridis",
                vmin=common_min,
                vmax=common_max,
            )
            ax.set(
                title=f"{case_name}\nLayer {idx + 1}/{N_LAYERS}",
                xlabel="x",
                ylabel="y",
            )
            fig.colorbar(image, ax=ax, label="printed height")

            metric_ax = fig.add_subplot(gs[metric_row, col])
            metric_ax.set_axis_off()
            metric_ax.text(
                0.5,
                0.55,
                _metric_text(result["metrics"][idx]),
                ha="center",
                va="center",
                fontsize=15,
                fontweight="bold",
                transform=metric_ax.transAxes,
                bbox={
                    "boxstyle": "round,pad=0.38",
                    "facecolor": "#f4f4f4",
                    "edgecolor": "#555555",
                    "linewidth": 1.1,
                },
            )

    fig.suptitle(
        f"Layer-by-layer policy comparison — {shape_name}",
        fontsize=26,
        y=0.995,
    )
    _finish_figure(fig, out_dir / "02_processing_layers_01_05_10.png")


def export_result(result: Dict[str, Any], out_dir: Path) -> None:
    np.savez_compressed(
        out_dir / "layer_by_layer_arrays.npz",
        final_target=result["final_target"],
        final_height=result["final_height"],
        layer_targets=result["layer_targets"],
        layer_heights=result["layer_heights"],
        desired_increments=result["desired_increments"],
        velocities=result["velocities"],
        base_velocities=result["base_velocities"],
        dvs=result["dvs"],
        offsets=result["offsets"],
    )

    metric_fields = ["layer"] + list(result["metrics"][0].keys())
    with open(out_dir / "layer_metrics.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=metric_fields)
        writer.writeheader()
        for idx, metric in enumerate(result["metrics"], start=1):
            writer.writerow({"layer": idx, **metric})

    with open(out_dir / "final_metrics.json", "w", encoding="utf-8") as f:
        json.dump(result["final_metrics"], f, indent=2)

    with open(out_dir / "run_config.json", "w", encoding="utf-8") as f:
        json.dump(
            {
                **asdict(CFG),
                "n_layers": N_LAYERS,
                "layer_thickness": LAYER_THICKNESS,
                "model_path": str(MODEL_PATH),
                "vecnormalize_path": str(VECNORMALIZE_PATH),
                "deterministic_action": DETERMINISTIC_ACTION,
                "shape_name": result["shape_name"],
                "case_name": result["case_name"],
                "use_rl": result["use_rl"],
                "execution_modified": result["execution_modified"],
            },
            f,
            indent=2,
        )


def save_all_outputs(case_results: Dict[str, Dict[str, Any]]) -> None:
    first_result = next(iter(case_results.values()))
    out_dir = OUTPUT_DIR / first_result["shape_name"]
    out_dir.mkdir(parents=True, exist_ok=True)
    # Remove figures from earlier runs so that each shape directory contains
    # exactly the two thesis figures generated below.
    for old_figure in out_dir.glob("*.png"):
        old_figure.unlink()
    for case_name, result in case_results.items():
        case_dir = out_dir / case_name.replace("/", "_")
        case_dir.mkdir(parents=True, exist_ok=True)
        export_result(result, case_dir)

    # Figure 1 retains the detailed RL/modified target/surface visualization.
    plot_final_target_and_selected_layers(case_results["RL/modified"], out_dir)
    # Figure 2 is the requested three-case, three-layer comparison.
    plot_selected_policy_comparison(case_results, out_dir)


def print_final_table(results: List[Dict[str, Any]]) -> None:
    print("\n" + "=" * 105)
    print(
        f"{'shape / case':38s} {'RelMSE':>12s} {'MSE':>12s} {'maxOv':>12s} "
        f"{'maxUnder':>12s} {'volumeErr':>12s}"
    )
    print("-" * 105)
    for result in results:
        m = result["final_metrics"]
        label = f"{result['shape_name']} | {result['case_name']}"
        print(
            f"{label:38s} "
            f"{m['relative_mse']:12.4e} {m['mse']:12.4e} "
            f"{m['max_overshoot']:12.4e} {m['max_undershoot']:12.4e} "
            f"{m['volume_error']:12.3%}"
        )
    print("=" * 105)



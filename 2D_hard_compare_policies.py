def surface_metrics(height: np.ndarray, target: np.ndarray) -> Dict[str, float]:
    h = height.astype(np.float64)
    t = target.astype(np.float64)
    err = h - t
    mse = float(np.mean(err**2))
    mae = float(np.mean(np.abs(err)))
    mean_t = float(np.mean(t))
    active = t > 1e-9
    active_mse = float(np.mean(err[active] ** 2)) if np.any(active) else float("nan")
    overshoot = np.maximum(err, 0.0)
    undershoot = np.maximum(-err, 0.0)
    target_volume = float(np.sum(t))
    volume_error = float(abs(np.sum(h) - target_volume) / max(target_volume, 1e-12))
    return {
        "mse": mse,
        "relative_mse": mse / max(mean_t**2, 1e-12),
        "mae": mae,
        "active_mse": active_mse,
        "max_abs_error": float(np.max(np.abs(err))),
        "max_overshoot": float(np.max(overshoot)),
        "mean_overshoot": float(np.mean(overshoot)),
        "max_undershoot": float(np.max(undershoot)),
        "volume_error": volume_error,
        "mean_height": float(np.mean(h)),
        "mean_target": mean_t,
    }


def normalize_observation(
    obs: Dict[str, np.ndarray],
    vecnorm: VecNormalize,
) -> Dict[str, np.ndarray]:
    batched = {key: value[None, ...] for key, value in obs.items()}
    return vecnorm.normalize_obs(batched)



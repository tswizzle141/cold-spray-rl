class AdaptiveSlicer:
    """
    Same LSQ slicer formulation as sb3_cold_spray_generalized_gaussian_ppo_13:
    the nonnegative variables are mass(step, offset_lane), with mass, step and
    lane smoothness regularization.  The solution is collapsed to one velocity
    and one baseline offset per snake step.

    Slicer planning always uses the original nominal Gaussian kernel.
    """

    def __init__(self, cfg: Config, steps: List[dict], deposition: DepositionModel2D):
        self.cfg = cfg
        self.steps = steps
        print("[INFO] Building nominal slicer basis once ...")
        self.offset_lanes = np.linspace(
            -cfg.off_max, cfg.off_max, cfg.n_offset_lanes, dtype=np.float64
        )
        columns = []
        for st in steps:
            for lane_off in self.offset_lanes:
                x0, y0, x1, y1 = clipped_shifted_segment(st, float(lane_off))
                columns.append(
                    deposition.basis_for_segment(
                        x0, y0, x1, y1, modified=False
                    ).reshape(-1)
                )
        self.B = np.stack(columns, axis=1).astype(np.float64)

        n_steps = len(steps)
        n_lanes = cfg.n_offset_lanes
        d_step = sparse.diags(
            [np.ones(n_steps - 1), -np.ones(n_steps - 1)],
            [0, 1],
            shape=(n_steps - 1, n_steps),
            format="csr",
        )
        d_lane = sparse.diags(
            [np.ones(n_lanes - 1), -np.ones(n_lanes - 1)],
            [0, 1],
            shape=(n_lanes - 1, n_lanes),
            format="csr",
        )
        self.D_step = sparse.kron(d_step, sparse.eye(n_lanes), format="csr")
        self.D_lane = sparse.kron(sparse.eye(n_steps), d_lane, format="csr")
        print(f"[OK] Nominal basis shape: {self.B.shape}")

    def plan(
        self, desired_increment: np.ndarray
    ) -> Tuple[np.ndarray, np.ndarray, Dict[str, float]]:
        c = self.cfg
        target = np.maximum(desired_increment, 0.0).astype(np.float64).reshape(-1)
        pixel_w = np.ones_like(target)
        pixel_w[target > 1e-12] = c.positive_target_weight
        sqrt_w = np.sqrt(pixel_w)

        A_data = sparse.csr_matrix(self.B * sqrt_w[:, None])
        b_data = target * sqrt_w
        blocks = [A_data]
        rhs = [b_data]
        n_vars = self.B.shape[1]

        if c.lambda_mass > 0:
            blocks.append(np.sqrt(c.lambda_mass) * sparse.eye(n_vars, format="csr"))
            rhs.append(np.zeros(n_vars))
        if c.lambda_step_smooth > 0:
            blocks.append(np.sqrt(c.lambda_step_smooth) * self.D_step)
            rhs.append(np.zeros(self.D_step.shape[0]))
        if c.lambda_lane_smooth > 0:
            blocks.append(np.sqrt(c.lambda_lane_smooth) * self.D_lane)
            rhs.append(np.zeros(self.D_lane.shape[0]))

        sol = lsq_linear(
            sparse.vstack(blocks, format="csr"),
            np.concatenate(rhs),
            bounds=(0.0, np.inf),
            method="trf",
            lsmr_tol="auto",
            max_iter=c.slicer_max_iter,
        )
        mass = sol.x.reshape(len(self.steps), c.n_offset_lanes)
        mass_per_step = np.sum(mass, axis=1)
        v_base = np.empty(len(self.steps), dtype=np.float32)
        offset_base = np.empty(len(self.steps), dtype=np.float32)
        for i, st in enumerate(self.steps):
            if mass_per_step[i] <= 1e-12:
                v_base[i] = c.v_max
                offset_base[i] = 0.0
            else:
                dt = mass_per_step[i] / max(c.feed_rate, 1e-12)
                v_base[i] = np.clip(st["length"] / max(dt, 1e-12), c.v_min, c.v_max)
                # Match the SB3 reference code: select the lane with maximum mass.
                offset_base[i] = self.offset_lanes[int(np.argmax(mass[i]))]

        reconstruction = (self.B @ mass.reshape(-1)).reshape(c.grid_n, c.grid_n)
        info = {
            "lsq_cost": float(sol.cost),
            "lsq_success": bool(sol.success),
            "slicer_reconstruction_mse": float(
                np.mean((reconstruction - desired_increment) ** 2)
            ),
        }
        return v_base, offset_base, info


